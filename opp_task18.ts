/**
 * СИТУАЦИЯ 1. Допустимы бессмысленные переходы
 * --------------------------------------------
 * В Шаге 1 можно сколько угодно раз вызывать complete() у уже
 * завершённой задачи. Объект не сопротивляется.
 */

/**
 * СИТУАЦИЯ 2. Что такое инвариант
 * -------------------------------
 * Инвариант — условие, которое ОБЯЗАНО выполняться всегда.
 * Для нашего Todo это правила переходов. Если инвариант нарушается,
 * объект находится в некорректном состоянии — и доверять ему нельзя.
 */

/**
 * ============================================================
 * ШАГ 3. С ИНВАРИАНТАМИ
 * ============================================================
 * Методы проверяют текущее состояние и разрешают только
 * допустимые переходы.
 */
namespace WithInvariants {
  type TodoStatus = "active" | "completed";

  class Todo {
    private status: TodoStatus = "active";

    /** Завершить можно только активную задачу. */
    complete(): void {
      if (this.status !== "active") {
        throw new Error("Завершить можно только активную задачу");
      }
      this.status = "completed";
    }

    /** Переоткрыть можно только завершённую задачу. */
    reopen(): void {
      if (this.status !== "completed") {
        throw new Error("Переоткрыть можно только завершённую задачу");
      }
      this.status = "active";
    }

    getStatus(): TodoStatus {
      return this.status;
    }
  }

  const todo = new Todo();
  todo.complete();
  console.log("[with-invariants] статус:", todo.getStatus());

  /** Теперь недопустимый переход невозможен. */
  // todo.complete();  // ❌ бросит ошибку
}

/**
 * ============================================================
 * ШАГ 4. СРАВНЕНИЕ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Объект всегда в корректном состоянии
 * С инвариантами объект НЕ МОЖЕТ оказаться в недопустимом
 * состоянии. Любой переход проверяется.
 *
 * СИТУАЦИЯ 2. Инвариант живёт в одном месте
 * Правило перехода записано в методе. Оно не расползается по коду.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Мы добавили инварианты: объект разрешает только допустимые
 * переходы и всегда остаётся в корректном состоянии.
 *
 * Ситуация              | Без инвариантов       | С инвариантами
 * ----------------------|-----------------------|---------------------------
 * Недопустимый переход  | возможен              | бросает ошибку
 * Состояние объекта     | может быть битым      | всегда корректно
 * Правило перехода      | отсутствует           | в методе
 *
 * Инвариант — ключевое понятие: объект, который следит за своими
 * инвариантами, становится надёжной единицей системы.
 *
 * Дальше зададимся вопросом: а КТО вообще должен знать правило?
 */