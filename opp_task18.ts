/**
 * ============================================================
 * ЗАДАЧА 18. ИНВАРИАНТЫ
 * Блок 3. Ответственность объекта
 * ============================================================
 *
 * В Задаче 17 мы защитили состояние: менять его можно только
 * через методы. Но методы пока ничего не проверяют. Значит,
 * объект может оказаться в НЕДОПУСТИМОМ состоянии — например,
 * «завершить» уже завершённую задачу.
 *
 * Здесь вводим инварианты: разрешаем только допустимые переходы.
 *
 * ИНВАРИАНТ — это условие, которое должно быть истинным всегда.
 * Здесь инвариант жизненного цикла:
 *   завершить можно только активную задачу;
 *   переоткрыть можно только завершённую.
 *
 * ЗАДАНИЕ:
 *   - Разреши только допустимые переходы состояний.
 *
 * Читай файл сверху вниз. Запусти его и посмотри на вывод.
 */

/**
 * ============================================================
 * ШАГ 1. БЕЗ ИНВАРИАНТОВ (проблема)
 * ============================================================
 */
namespace WithoutInvariants {
  type TodoStatus = "active" | "completed";

  class Todo {
    private status: TodoStatus = "active";

    /** Методы не проверяют текущее состояние. */
    complete(): void {
      this.status = "completed";
    }

    reopen(): void {
      this.status = "active";
    }

    getStatus(): TodoStatus {
      return this.status;
    }
  }

  const todo = new Todo();
  todo.complete();
  todo.complete(); // «завершили» уже завершённую — и никакой ошибки
  console.log("[no-invariants] статус:", todo.getStatus());

  /**
   * Объект позволил бессмысленное действие. Инварианта нет —
   * объект не следит за корректностью своего жизненного цикла.
   */
}

