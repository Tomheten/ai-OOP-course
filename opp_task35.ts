/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Дублирование ответственности — когда одна и та же обязанность
 * живёт в нескольких местах. Это всегда признак проблемы.
 *
 * Как найти:
 *   - ищи одинаковые проверки в разных классах;
 *   - ищи одинаковую логику в разных местах;
 *   - спрашивай себя: «если поменяю здесь, нужно ли менять там?»
 *
 * Как убрать:
 *   - определи, кто ДОЛЖЕН владеть этой ответственностью;
 *   - перенеси её туда;
 *   - удали из остальных мест.
 *
 * Дальше посмотрим, кто должен кем управлять в системе объектов.
 */