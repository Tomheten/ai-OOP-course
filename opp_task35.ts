/**
 * СИТУАЦИЯ 1. Правило заголовка в двух местах
 * -------------------------------------------
 * В Шаге 1 правило «заголовок не может быть пустым» проверяется
 * и в конструкторе Note, и в NoteEditor.createNote.
 *
 * Что плохо:
 *   - если правило изменится, нужно помнить про оба места;
 *   - можно легко забыть про одно из них;
 *   - непонятно, кто ОТВЕЧАЕТ за это правило.
 */

/**
 * СИТУАЦИЯ 2. Логирование в двух местах
 * -------------------------------------
 * Запись о действиях ведётся и в редакторе, и в хранилище.
 * Это одна ответственность (журналирование), размазанная по
 * двум классам.
 */

/**
 * СИТУАЦИЯ 3. Как найти дублирование?
 * -----------------------------------
 * Задай себе вопросы:
 *   - Где это правило уже проверяется?
 *   - Кто ещё делает ту же работу?
 *   - Если я поменяю это здесь, нужно ли менять где-то ещё?
 *
 * Если на последний вопрос ответ «да» — у тебя дублирование
 * ответственности.
 */

/**
 * ============================================================
 * ШАГ 3. УБИРАЕМ ДУБЛИРОВАНИЕ
 * ============================================================
 */
namespace WithoutDuplication {
  class Note {
    private title: string;

    constructor(title: string) {
      /** Единственное место, где живёт правило заголовка. */
      if (!title.trim()) {
        throw new Error("Заголовок не может быть пустым");
      }
      this.title = title;
    }

    getTitle(): string {
      return this.title;
    }
  }

  class NoteStore {
    private notes: Note[] = [];

    add(note: Note): void {
      this.notes.push(note);
    }

    getAll(): Note[] {
      return [...this.notes];
    }
  }

  class NoteEditor {
    private readonly store: NoteStore;

    constructor(store: NoteStore) {
      this.store = store;
    }

    createNote(title: string): Note {
      /**
       * Проверку убрали. Она уже есть в конструкторе Note.
       * Если заголовок пустой — Note сам выбросит ошибку.
       */
      const note = new Note(title);
      this.store.add(note);
      return note;
    }
  }

  const store = new NoteStore();
  const editor = new NoteEditor(store);
  editor.createNote("Идеи");

  /** Правило сработает из одного места: */
  // editor.createNote(""); // ❌ выбросит ошибку из конструктора Note

  console.log("[clean] система без дублирования");
}

