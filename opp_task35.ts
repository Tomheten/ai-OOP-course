/**
 * ============================================================
 * ШАГ 1. СИСТЕМА С ДУБЛИРОВАНИЕМ
 * ============================================================
 * Посмотри внимательно на код. Где здесь одна и та же
 * ответственность встречается дважды?
 */
namespace DuplicatedResponsibilities {
  class Note {
    private title: string;

    constructor(title: string) {
      /** Проверка заголовка — ПЕРВОЕ место. */
      if (!title.trim()) {
        throw new Error("Заголовок не может быть пустым");
      }
      this.title = title;
    }

    getTitle(): string {
      return this.title;
    }
  }

  class NoteStore {
    private notes: Note[] = [];

    add(note: Note): void {
      this.notes.push(note);
    }

    getAll(): Note[] {
      return [...this.notes];
    }
  }

  class NoteEditor {
    private readonly store: NoteStore;

    constructor(store: NoteStore) {
      this.store = store;
    }

    createNote(title: string): Note {
      /** Проверка заголовка — ВТОРОЕ место. То же самое правило! */
      if (!title.trim()) {
        throw new Error("Заголовок не может быть пустым");
      }
      const note = new Note(title);
      this.store.add(note);
      return note;
    }

    /** И ещё: история пишется и в редакторе, и в хранилище. */
    private log(message: string): void {
      console.log(`[editor] ${message}`);
    }
  }

  class NoteStoreWithLog {
    private notes: Note[] = [];

    add(note: Note): void {
      this.notes.push(note);
      /** История пишется ЗДЕСЬ — дублирует редактор. */
      console.log(`[store] добавлена заметка`);
    }
  }

  const store = new NoteStore();
  const editor = new NoteEditor(store);
  editor.createNote("Идеи");
  console.log("[duplicated] система работает, но с дублированием");
}

