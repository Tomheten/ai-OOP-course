/**
 * СИТУАЦИЯ 1. Четыре объекта, четыре ответственности
 * --------------------------------------------------
 *   - Note      — содержимое заметки;
 *   - NoteStore — хранение;
 *   - Autosave  — периодическое сохранение;
 *   - NoteEditor — координация.
 *
 * Каждый объект делает одно дело.
 */

/**
 * СИТУАЦИЯ 2. Автосохранение можно отключить
 * -------------------------------------------
 * Если автосохранение не нужно (например, в тестах), просто
 * не создаём объект Autosave. Редактор и хранилище работают
 * как обычно.
 */

/**
 * СИТУАЦИЯ 3. Интервал можно настроить
 * -------------------------------------
 * Интервал передаётся в конструктор. Не нужно лезть в код
 * редактора, чтобы поменять период сохранения.
 */

/**
 * СИТУАЦИЯ 4. Объекты связаны, но не сцеплены
 * -------------------------------------------
 * Autosave знает про хранилище (ему нужно знать, что сохранять).
 * Но редактор не знает про автосохранение. Хранилище не знает
 * про автосохранение. Связи односторонние.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Мы добавили автосохранение как отдельный объект. Система
 * выросла до четырёх объектов, и каждый отвечает за своё.
 *
 * Это и есть взаимодействие объектов: не один огромный класс,
 * а много маленьких, каждый из которых знает только своё дело.
 *
 * Ситуация              | Автосохранение в редакторе | Отдельный объект
 * ----------------------|----------------------------|---------------------------
 * Ответственностей      | 2                          | 1 + 1
 * Можно отключить       | сложно                     | просто
 * Настройка интервала   | в коде редактора           | в конструкторе
 * Тестирование          | сложнее                    | проще
 *
 * Дальше посмотрим, как находить и устранять неправильное
 * распределение ответственности.
 */