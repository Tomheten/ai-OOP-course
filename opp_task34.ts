/**
 * Первое, что приходит в голову — добавить автосохранение прямо
 * в редактор:
 *
 *   class NoteEditor {
 *     startAutosave() {
 *       setInterval(() => {
 *         // сохранить все заметки
 *       }, 5000);
 *     }
 *   }
 *
 * Но это снова две ответственности в одном классе: координация
 * и автосохранение.
 */

/**
 * ============================================================
 * ШАГ 2. РЕШЕНИЕ: ОТДЕЛЬНЫЙ ОБЪЕКТ ДЛЯ АВТОСОХРАНЕНИЯ
 * ============================================================
 */
namespace AutosaveSystem {
  class Note {
    private title: string;

    constructor(title: string) {
      this.title = title;
    }

    getTitle(): string {
      return this.title;
    }
  }

  /** Хранилище — отдельная ответственность. */
  class NoteStore {
    private notes: Note[] = [];

    add(note: Note): void {
      this.notes.push(note);
    }

    getAll(): Note[] {
      return [...this.notes];
    }
  }

  /** Автосохранение — тоже отдельная ответственность. */
  class Autosave {
    private readonly store: NoteStore;
    private readonly intervalMs: number;
    private timer: ReturnType<typeof setInterval> | null = null;

    constructor(store: NoteStore, intervalMs: number) {
      this.store = store;
      this.intervalMs = intervalMs;
    }

    start(): void {
      if (this.timer) return;
      this.timer = setInterval(() => {
        const count = this.store.getAll().length;
        console.log(`[autosave] сохраняем ${count} заметок`);
      }, this.intervalMs);
    }

    stop(): void {
      if (this.timer) {
        clearInterval(this.timer);
        this.timer = null;
      }
    }
  }

  /** Редактор — координатор, не тащит автосохранение на себе. */
  class NoteEditor {
    private readonly store: NoteStore;

    constructor(store: NoteStore) {
      this.store = store;
    }

    createNote(title: string): Note {
      const note = new Note(title);
      this.store.add(note);
      return note;
    }
  }

  /**
   * Использование: все объекты сотрудничают.
   *
   * Для демонстрации мы не будем реально ждать таймер,
   * а покажем структуру. В реальном коде здесь был бы
   * запуск автосохранения.
   */
  const store = new NoteStore();
  const editor = new NoteEditor(store);
  const autosave = new Autosave(store, 5000);

  editor.createNote("Идеи");
  editor.createNote("Покупки");

  /** В реальном коде: */
  // autosave.start();
  // ... пользователь работает ...
  // autosave.stop();

  console.log("[autosave] система собрана");
  console.log("[autosave] заметок в хранилище:", store.getAll().length);
}

