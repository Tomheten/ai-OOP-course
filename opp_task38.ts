/**
 * СИТУАЦИЯ 1. Импорт и экспорт — разные ответственности
 * -----------------------------------------------------
 * Экспорт превращает заметки в текст/JSON. Импорт превращает
 * текст/JSON в заметки. Это разные операции, и они живут в
 * разных классах.
 */

/**
 * СИТУАЦИЯ 2. Система растёт
 * --------------------------
 * Теперь у нас:
 *   - Note          — сама заметка;
 *   - NoteStore     — хранение;
 *   - NoteEditor    — координация создания;
 *   - History       — история изменений;
 *   - Autosave      — автосохранение;
 *   - NoteExporter  — экспорт;
 *   - NoteImporter  — импорт.
 *
 * Семь классов, и каждый делает только своё.
 */

