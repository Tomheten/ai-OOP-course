/**
 * ============================================================
 * ШАГ 1. БАЗОВАЯ РЕАЛИЗАЦИЯ
 * ============================================================
 */
namespace JsonImport {
  /** Данные, которые мы импортируем. */
  type Record = {
    id: number;
    name: string;
    value: number;
  };

  /** Импортер для JSON. Пока один формат. */
  class JsonImporter {
    import(content: string): Record[] {
      const data = JSON.parse(content);
      return data.map((item: Record) => ({
        id: item.id,
        name: item.name,
        value: item.value,
      }));
    }
  }

  /** Использование. */
  const jsonContent = JSON.stringify([
    { id: 1, name: "Первый", value: 100 },
    { id: 2, name: "Второй", value: 200 },
  ]);

  const importer = new JsonImporter();
  const records = importer.import(jsonContent);

  console.log("[json] импортировано:", records.length, "записей");
  console.log("[json] первая запись:", records[0]);
}

