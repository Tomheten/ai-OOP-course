namespace TheWholePicture {
  type UserRole = "user" | "admin";
  type UserStatus = "active" | "banned" | "pending";

  /** Пустой User. Только данные. */
  class User {
    id: number;
    name: string;
    email: string;
    role: UserRole;
    status: UserStatus;

    constructor(id: number, name: string, email: string, role: UserRole, status: UserStatus) {
      this.id = id;
      this.name = name;
      this.email = email;
      this.role = role;
      this.status = status;
    }
  }

  /** Логика изменений. */
  class UserService {
    updateName(user: User, newName: string): void {
      user.name = newName;
    }
    promoteToAdmin(user: User): void {
      user.role = "admin";
    }
  }

  /** Логика валидации. */
  class UserValidator {
    validate(user: User): boolean {
      return !!user.name.trim() && user.email.includes("@");
    }
  }

  /** Логика прав. */
  class UserPermissionService {
    canDeletePost(user: User): boolean {
      return user.role === "admin";
    }
    canBanUser(user: User): boolean {
      return user.role === "admin";
    }
  }

  /** Логика статусов. */
  class UserStatusService {
    activate(user: User): void {
      if (user.status !== "pending") throw new Error("Только pending");
      user.status = "active";
    }
    ban(user: User): void {
      if (user.status !== "active") throw new Error("Только active");
      user.status = "banned";
    }
  }

  const user = new User(1, "Иван", "ivan@example.com", "user", "pending");
  const userService = new UserService();
  const validator = new UserValidator();
  const perms = new UserPermissionService();
  const statuses = new UserStatusService();

  statuses.activate(user);
  console.log("[whole] статус:", user.status);
  console.log("[whole] валиден:", validator.validate(user));
  console.log("[whole] can ban:", perms.canBanUser(user));
}

