/**
 * Разберём, из чего складывалось поведение в дереве:
 *
 *   1. КАНАЛ доставки (email, sms) — как отправляем;
 *   2. СРОЧНОСТЬ (обычное, срочное) — как помечаем;
 *   3. ВЛОЖЕНИЕ (нет, есть) — что прикладываем.
 *
 * Это ТРИ НЕЗАВИСИМЫХ измерения. В наследовании они склеились
 * в одну иерархию. В композиции каждое измерение станет
 * отдельным объектом, который можно свободно комбинировать.
 */

/**
 * ============================================================
 * ШАГ 3. СТАЛО: КОМПОЗИЦИЯ
 * ============================================================
 */
namespace AfterRefactor {
  /** Измерение 1: канал доставки. */
  interface DeliveryChannel {
    deliver(message: string): void;
  }

  class EmailChannel implements DeliveryChannel {
    deliver(message: string): void {
      console.log(`[EMAIL] ${message}`);
    }
  }

  class SmsChannel implements DeliveryChannel {
    deliver(message: string): void {
      console.log(`[SMS] ${message}`);
    }
  }

  /** Измерение 2 и 3: модификаторы сообщения. */
  interface MessageModifier {
    modify(message: string): string;
  }

  class UrgentModifier implements MessageModifier {
    modify(message: string): string {
      return `[СРОЧНО] ${message}`;
    }
  }

  class AttachmentModifier implements MessageModifier {
    modify(message: string): string {
      return `${message} [вложение: файл]`;
    }
  }

  /**
   * Один класс уведомления. Канал и модификаторы передаются
   * через композицию. Никаких подклассов.
   */
  class Notification {
    constructor(
      private message: string,
      private channel: DeliveryChannel,
      private modifiers: MessageModifier[] = []
    ) {}

    send(): void {
      /** Применяем модификаторы по очереди. */
      let result = this.message;
      for (const modifier of this.modifiers) {
        result = modifier.modify(result);
      }
      /** Передаём каналу. */
      this.channel.deliver(result);
    }
  }

  /**
   * Любая комбинация — один и тот же класс.
   * Никакого комбинаторного взрыва.
   */
  new Notification("Привет", new EmailChannel()).send();
  new Notification("Привет", new SmsChannel(), [new UrgentModifier()]).send();
  new Notification(
    "Привет",
    new EmailChannel(),
    [new UrgentModifier(), new AttachmentModifier()]
  ).send();
}

