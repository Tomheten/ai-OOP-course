/**
 * СИТУАЦИЯ 2. Экспорт можно переиспользовать
 * ------------------------------------------
 * Нужен экспорт в отчёте? Создай NoteExporter с нужными заметками.
 * Не нужен редактор.
 */

/**
 * СИТУАЦИЯ 3. Новый формат — новый метод
 * ---------------------------------------
 * Если нужен экспорт в Markdown или в HTML, добавляем метод в
 * NoteExporter. Редактор не меняется.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Мы выделили экспорт в отдельный класс. Это классический приём:
 * если появляется новая ответственность, выделяем её в отдельный
 * класс.
 *
 * Ситуация              | Экспорт в редакторе  | Отдельный класс
 * ----------------------|----------------------|---------------------------
 * Ответственностей      | 2+                   | 1 + 1
 * Переиспользование     | нельзя               | можно
 * Новый формат          | редактор растёт      | экспортёр растёт
 *
 * Дальше добавим импорт — противоположность экспорта.
 */