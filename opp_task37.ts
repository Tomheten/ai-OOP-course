/**
 * СИТУАЦИЯ 1. Редактор распухает
 * ------------------------------
 * Каждый новый формат экспорта добавляет метод в редактор.
 * Через некоторое время редактор делает всё: создаёт заметки,
 * хранит их, экспортирует, импортирует, логирует.
 */

/**
 * СИТУАЦИЯ 2. Экспорт нельзя переиспользовать
 * --------------------------------------------
 * Если нужно экспортировать заметки где-то ещё (например, в
 * отчёте), придётся либо вызывать редактор, либо дублировать код.
 */

/**
 * ============================================================
 * ШАГ 3. ЭКСПОРТ КАК ОТДЕЛЬНЫЙ КЛАСС
 * ============================================================
 */
namespace ExportAsSeparateClass {
  class Note {
    private title: string;
    private content: string;

    constructor(title: string, content: string) {
      this.title = title;
      this.content = content;
    }

    getTitle(): string {
      return this.title;
    }

    getContent(): string {
      return this.content;
    }
  }

  /** Отдельная ответственность: экспорт заметок. */
  class NoteExporter {
    constructor(private notes: Note[]) {}

    exportAsText(): string {
      return this.notes
        .map((n) => `${n.getTitle()}: ${n.getContent()}`)
        .join("\n");
    }

    exportAsJson(): string {
      const data = this.notes.map((n) => ({
        title: n.getTitle(),
        content: n.getContent(),
      }));
      return JSON.stringify(data, null, 2);
    }
  }

  /** Редактор не знает про экспорт. */
  class NoteEditor {
    private notes: Note[] = [];

    addNote(note: Note): void {
      this.notes.push(note);
    }

    getNotes(): Note[] {
      return [...this.notes];
    }
  }

  /** Использование: экспорт — отдельный объект. */
  const editor = new NoteEditor();
  editor.addNote(new Note("Идеи", "Сделать проект"));
  editor.addNote(new Note("Покупки", "Молоко"));

  const exporter = new NoteExporter(editor.getNotes());
  console.log("[separate] текст:\n" + exporter.exportAsText());
  console.log("[separate] json:\n" + exporter.exportAsJson());
}

