/**
 * ============================================================
 * ШАГ 1. СОБЛАЗН: ЭКСПОРТ В РЕДАКТОРЕ
 * ============================================================
 * Первое, что приходит в голову — добавить метод экспорта в
 * редактор. Но это снова две ответственности в одном классе.
 */
namespace ExportInsideEditor {
  class Note {
    private title: string;
    private content: string;

    constructor(title: string, content: string) {
      this.title = title;
      this.content = content;
    }

    getTitle(): string {
      return this.title;
    }

    getContent(): string {
      return this.content;
    }
  }

  class NoteEditor {
    private notes: Note[] = [];

    addNote(note: Note): void {
      this.notes.push(note);
    }

    /** Экспорт прямо здесь — вторая ответственность. */
    exportAsText(): string {
      return this.notes
        .map((n) => `${n.getTitle()}: ${n.getContent()}`)
        .join("\n");
    }

    /** И ещё формат — третья ответственность. */
    exportAsJson(): string {
      return JSON.stringify(this.notes);
    }
  }

  const editor = new NoteEditor();
  editor.addNote(new Note("Идеи", "Сделать проект"));
  console.log("[inside] экспорт:", editor.exportAsText());
}

