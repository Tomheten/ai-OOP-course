/**
 * УШЛИ:
 *   - UserService           → поведение в User;
 *   - UserValidator         → правила в конструкторе и методах;
 *   - UserPermissionService → права в методах User;
 *   - UserStatusService     → жизненный цикл в методах User.
 *
 * ОСТАЛСЯ:
 *   - UserRepository        → работа с внешним миром.
 *
 * Почему репозиторий остался? Потому что сохранение в БД — это
 * не бизнес-правило. User не должен знать про базу данных.
 * Это работа инфраструктуры.
 */

/**
 * ============================================================
 * ШАГ 4. КРИТЕРИЙ: ЧТО ОСТАВЛЯТЬ В СЕРВИСАХ
 * ============================================================
 */

/**
 * Сервисы нужны, когда:
 *
 *   1. Работа с внешним миром.
 *      База данных, API, файловая система, почта.
 *      Сущность не должна знать про инфраструктуру.
 *
 *   2. Координация нескольких сущностей.
 *      Если правило касается нескольких объектов сразу,
 *      оно живёт в сервисе (или доменном сервисе).
 *
 *   3. Сложные процессы.
 *      Сценарии, которые не принадлежат одной сущности.
 *
 * Сервисы НЕ нужны, когда:
 *
 *   - Правило касается только состояния одной сущности.
 *     Такое правило должно жить в самой сущности.
 *
 *   - Сервис — это просто «прослойка» между клиентом и сущностью.
 *     Если сервис ничего не делает, кроме вызова методов сущности,
 *     он лишний.
 */

