/**
 * ============================================================
 * ШАГ 2. СТАЛО: ОДИН КЛАСС + СЕРВИСЫ ДЛЯ ВНЕШНЕГО МИРА
 * ============================================================
 */
namespace AfterRefactor {
  type UserRole = "user" | "admin";
  type UserStatus = "active" | "banned" | "pending";

  /** Rich User: все правила о себе самом. */
  class User {
    private readonly id: number;
    private name: string;
    private email: string;
    private role: UserRole;
    private status: UserStatus;

    constructor(id: number, name: string, email: string, role: UserRole) {
      this.id = id;
      this.setName(name);
      this.setEmail(email);
      this.role = role;
      this.status = "pending";
    }

    setName(name: string): void {
      if (!name.trim()) throw new Error("Имя не может быть пустым");
      this.name = name;
    }

    setEmail(email: string): void {
      if (!email.includes("@")) throw new Error("Некорректный email");
      this.email = email;
    }

    activate(): void {
      if (this.status !== "pending") throw new Error("Только pending");
      this.status = "active";
    }

    ban(): void {
      if (this.status !== "active") throw new Error("Только active");
      this.status = "banned";
    }

    canDeletePost(): boolean {
      return this.role === "admin";
    }

    getStatus(): UserStatus {
      return this.status;
    }
  }

  /**
   * А этот сервис НУЖЕН. Он работает с внешним миром —
   * сохраняет пользователей в базу. Это не бизнес-логика,
   * это инфраструктура.
   */
  class UserRepository {
    private users: Map<number, User> = new Map();

    save(user: User): void {
      console.log(`[repository] сохраняем пользователя`);
      // здесь был бы реальный вызов БД
    }

    findById(id: number): User | undefined {
      return this.users.get(id);
    }
  }

  const user = new User(1, "Иван", "ivan@example.com", "user");
  user.activate();

  const repo = new UserRepository();
  repo.save(user);

  console.log("[after-refactor] статус:", user.getStatus());
}

