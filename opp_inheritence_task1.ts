/**
 * ============================================================
 * ШАГ 1. СЛУЧАЙ 1: ИЕРАРХИЯ ОШИБОК
 * ============================================================
 * Классический пример, где наследование уместно.
 */
namespace ErrorHierarchy {
  /** Базовый класс ошибки. */
  class AppError extends Error {
    constructor(message: string) {
      super(message);
      this.name = this.constructor.name;
    }
  }

  /** Конкретные ошибки наследуются от базовой. */
  class ValidationError extends AppError {}

  class NotFoundError extends AppError {}

  class PermissionError extends AppError {}

  /** Использование: можно ловить как общую, так и конкретную. */
  function doSomething(fail: boolean): void {
    if (fail) {
      throw new ValidationError("Некорректные данные");
    }
  }

  try {
    doSomething(true);
  } catch (e) {
    /** Ловим базовый тип — работает для всех подклассов. */
    if (e instanceof AppError) {
      console.log("[errors] поймана ошибка приложения:", e.message);
    }
    if (e instanceof ValidationError) {
      console.log("[errors] это именно ошибка валидации");
    }
  }
}

/**
 * ============================================================
 * ШАГ 2. СЛУЧАЙ 2: ОБЩИЙ ИНСТРУМЕНТ ДЛЯ РАЗНЫХ ТИПОВ
 * ============================================================
 */
namespace CommonBaseForShapes {
  /**
   * Абстрактная фигура. Задаёт контракт и общее поведение.
   * Здесь наследование уместно: у всех фигур ЕСТЬ площадь,
   * и они ДЕЙСТВИТЕЛЬНО являются фигурами.
   */
  abstract class Shape {
    /** Общее для всех фигур поведение. */
    abstract area(): number;

    /** Общая логика — наследуется. */
    describe(): string {
      return `Фигура с площадью ${this.area()}`;
    }
  }

  class Circle extends Shape {
    constructor(private radius: number) {
      super();
    }

    area(): number {
      return Math.PI * this.radius ** 2;
    }
  }

  class Square extends Shape {
    constructor(private side: number) {
      super();
    }

    area(): number {
      return this.side ** 2;
    }
  }

  const shapes: Shape[] = [new Circle(2), new Square(3)];
  for (const shape of shapes) {
    console.log("[shapes]", shape.describe());
  }
}

