/**
 * ============================================================
 * ШАГ 1. ЖУРНАЛ КАК ОТДЕЛЬНЫЙ КЛАСС
 * ============================================================
 */
namespace ActionLogSystem {
  class Note {
    private title: string;

    constructor(title: string) {
      this.title = title;
    }

    getTitle(): string {
      return this.title;
    }
  }

  class NoteStore {
    private notes: Note[] = [];

    add(note: Note): void {
      this.notes.push(note);
    }
  }

  /** Отдельная ответственность: журнал действий. */
  class ActionLog {
    private entries: { timestamp: string; action: string }[] = [];

    log(action: string): void {
      this.entries.push({
        timestamp: new Date().toISOString(),
        action,
      });
    }

    getEntries(): { timestamp: string; action: string }[] {
      return [...this.entries];
    }
  }

  /** Координатор использует журнал. */
  class NoteEditorCoordinator {
    constructor(
      private store: NoteStore,
      private log: ActionLog
    ) {}

    createNote(title: string): Note {
      const note = new Note(title);
      this.store.add(note);
      this.log.log(`Создана заметка "${title}"`);
      return note;
    }
  }

  /** Использование: журнал — отдельный объект. */
  const store = new NoteStore();
  const log = new ActionLog();
  const coordinator = new NoteEditorCoordinator(store, log);

  coordinator.createNote("Идеи");
  coordinator.createNote("Покупки");

  console.log("[action-log] записей в журнале:", log.getEntries().length);
  console.log("[action-log] последняя:", log.getEntries().at(-1)?.action);
}

