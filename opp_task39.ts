/**
 * СИТУАЦИЯ 1. Журнал — сквозная функциональность
 * -----------------------------------------------
 * Логирование касается многих действий: создание, изменение,
 * удаление. Но логика логирования не должна быть размазана по
 * всем классам.
 */

/**
 * СИТУАЦИЯ 2. Координатор решает, что логировать
 * -----------------------------------------------
 * Координатор знает, какие действия происходят, и сообщает об
 * этом журналу. Журнал не знает про заметки или редактор — он
 * просто записывает.
 */

/**
 * СИТУАЦИЯ 3. Журнал можно переиспользовать
 * ------------------------------------------
 * Если нужно логировать что-то ещё (например, действия
 * пользователя в другой части системы), используем тот же
 * ActionLog.
 */

