/**
 * СИТУАЦИЯ 1. Распределение ответственности
 * ------------------------------------------
 * Посмотри на систему:
 *   - Note отвечает за СВОЁ содержимое (заголовок, текст);
 *   - User представляет владельца;
 *   - NoteEditor координирует создание и удаление.
 *
 * Каждый объект знает только своё.
 */

/**
 * СИТУАЦИЯ 2. Объекты общаются через методы
 * ------------------------------------------
 * Редактор не лезет внутрь заметки. Он вызывает её методы.
 * Заметка не знает про редактор. Она просто живёт своей жизнью.
 */

/**
 * СИТУАЦИЯ 3. Заметка защищает себя сама
 * ---------------------------------------
 * Если редактор попытается создать заметку с пустым заголовком,
 * выбросится ошибка. Это не редактор проверяет заголовок — это
 * заметка защищает себя.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Мы построили систему из трёх объектов, каждый из которых
 * отвечает за своё. Объекты сотрудничают, но не лезут друг
 * к другу внутрь.
 *
 * Ситуация              | Что делает
 * ----------------------|------------------------------------
 * Note                  | хранит и защищает своё содержимое
 * User                  | представляет владельца
 * NoteEditor            | координирует создание и удаление
 *
 * Дальше выделим новую ответственность: историю изменений.
 */