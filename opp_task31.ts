/**
 * В системе есть несколько объектов:
 *
 *   - Note       — сама заметка (богатая модель из Блока 3);
 *   - User       — пользователь, который создаёт заметки;
 *   - NoteEditor — редактор, который координирует действия.
 *
 * Каждый объект отвечает за своё. Вместе они образуют систему.
 */

/**
 * ============================================================
 * ШАГ 2. РЕАЛИЗАЦИЯ
 * ============================================================
 */
namespace NoteEditorSystem {
  /** Заметка — богатая модель. */
  class Note {
    private title: string;
    private content: string;
    private readonly createdAt: string;

    constructor(title: string, content: string) {
      this.setTitle(title);
      this.content = content;
      this.createdAt = new Date().toISOString();
    }

    private setTitle(title: string): void {
      if (!title.trim()) {
        throw new Error("Заголовок не может быть пустым");
      }
      this.title = title;
    }

    rename(title: string): void {
      this.setTitle(title);
    }

    updateContent(content: string): void {
      this.content = content;
    }

    getTitle(): string {
      return this.title;
    }

    getContent(): string {
      return this.content;
    }
  }

  /** Пользователь — владелец заметок. */
  class User {
    private readonly id: number;
    private name: string;

    constructor(id: number, name: string) {
      this.id = id;
      this.name = name;
    }

    getName(): string {
      return this.name;
    }
  }

  /**
   * Редактор — координатор. Он не владеет заметками,
   * а управляет действиями с ними.
   */
  class NoteEditor {
    private readonly owner: User;
    private notes: Note[] = [];

    constructor(owner: User) {
      this.owner = owner;
    }

    createNote(title: string, content: string): Note {
      const note = new Note(title, content);
      this.notes.push(note);
      console.log(`[editor] ${this.owner.getName()} создал заметку "${title}"`);
      return note;
    }

    deleteNote(note: Note): void {
      const index = this.notes.indexOf(note);
      if (index === -1) {
        throw new Error("Заметка не найдена");
      }
      this.notes.splice(index, 1);
      console.log(`[editor] заметка "${note.getTitle()}" удалена`);
    }

    listNotes(): Note[] {
      return [...this.notes];
    }
  }

  /** Использование: несколько объектов работают вместе. */
  const user = new User(1, "Иван");
  const editor = new NoteEditor(user);

  const note1 = editor.createNote("Идеи", "Сделать проект");
  const note2 = editor.createNote("Покупки", "Молоко, хлеб");

  note1.rename("Идеи для проекта");
  note1.updateContent("Сделать проект и запустить его");

  console.log("[system] заметок:", editor.listNotes().length);
  console.log("[system] первая заметка:", note1.getTitle());

  editor.deleteNote(note2);
  console.log("[system] заметок после удаления:", editor.listNotes().length);
}

