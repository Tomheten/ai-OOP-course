/**
 * СИТУАЦИЯ 1. Из чего состояла фабрика?
 * -------------------------------------
 * Посмотри на createConfig из Шага 1. Чтобы создать объект,
 * мы вручную:
 *   - завели переменные состояния (data, filePath);
 *   - написали функции-методы, которые это состояние используют;
 *   - вернули объект, связав их через замыкание.
 *
 * Это работает, но это «ручная сборка» объекта.
 */

/**
 * СИТУАЦИЯ 2. Что даст класс?
 * ---------------------------
 * Класс — это готовая «форма» для объекта:
 *   - поля описываются прямо (не через переменные замыкания);
 *   - конструктор отвечает за создание;
 *   - методы живут рядом с полями;
 *   - доступ управляется словами private / readonly.
 *
 * Посмотри на версию ниже и сравни с фабрикой.
 */

/**
 * ============================================================
 * ШАГ 3. СТАЛО: ПЕРВЫЙ КЛАСС
 * ============================================================
 * Та же конфигурация, но как класс.
 */
namespace ClassVersion {
  const fakeFs: Record<string, string> = {
    "config.json": JSON.stringify({ port: 3000, host: "localhost", debug: false }),
  };
  function readFile(path: string): string {
    return fakeFs[path];
  }
  function writeFile(path: string, content: string): void {
    fakeFs[path] = content;
  }

  type AppConfig = {
    port: number;
    host: string;
    debug: boolean;
  };

  /** Первый класс: данные и поведение объединены. */
  class Config {
    private data: AppConfig;
    /**private — поле видно только внутри класса. readonly —
     * его нельзя переприсвоить после конструктора.
     * Здесь путь не должен меняться всю жизнь объекта. */
    private readonly filePath: string;

    /** Конструктор отвечает за создание объекта. */
    constructor(filePath: string) {
      this.filePath = filePath;
      this.data = JSON.parse(readFile(filePath));
    }

    getSource(): string {
      return this.filePath;
    }

    save(): void {
      writeFile(this.filePath, JSON.stringify(this.data));
    }

    setParam(key: string, value: any): void {
      (this.data as any)[key] = value;
    }

    getParam(key: string): any {
      /**any здесь намеренно — это и есть "дырка". 
       * Мы принимаем ЛЮБОЕ значение без проверки. Дальше избавимся от этого. */
      return (this.data as any)[key];
    }
  }

  const config = new Config("config.json");
  config.setParam("port", 8080);
  config.save();
  console.log("[class] port =", config.getParam("port"));

  /**
   * НО: класс появился, а правила — нет.
   * Раскомментируй — и класс это спокойно проглотит:
   */
  // config.setParam("port", -1);   // никакой проверки!
}

/**
 * ============================================================
 * ШАГ 4. СРАВНЕНИЕ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Данные и поведение вместе
 * И фабрика, и класс объединяют данные и поведение. Но класс
 * делает это «из коробки»: поля, конструктор и методы описаны
 * в одном месте, без ручной сборки замыкания.
 *
 * СИТУАЦИЯ 2. Класс не решает всё автоматически
 * Обрати внимание: мы получили класс, но метод setParam всё ещё
 * принимает ЛЮБОЕ значение. Правило «порт должен быть корректным»
 * никуда не делось — его просто нет. Класс объединил данные
 * и поведение, но НЕ наделил объект ответственностью за правила.
 *
 * Сам факт появления слова class ещё не делает дизайн хорошим.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Открытие этой задачи:
 *   Класс способен объединять данные и поведение. Это готовый
 *   инструмент для того, что мы раньше собирали фабриками.
 *
 * Проблема, которую мы заметили:
 *   Сам по себе класс не решает архитектурные проблемы. Объект
 *   может быть классом, но оставаться «пустым» — без правил
 *   и ответственности.
 *
 * Ситуация               | Фабрика                 | Класс
 * -----------------------|-------------------------|---------------------------
 * Данные + поведение     | через замыкание         | поля + методы «из коробки»
 * Создание объекта       | вызов функции           | new + конструктор
 * Доступ к данным        | замыкание               | private / readonly
 * Правила состояния      | нет                     | пока тоже нет (!)
 *
 * Дальше наделим объект ответственностью: перенесём проверки
 * и правила внутрь класса.
 */