/**
 * ------------------------------------------------------------
 * ПРО СТРУКТУРУ ФАЙЛА
 * ------------------------------------------------------------
 * Ниже две версии: «было» (фабричная функция) и «стало» (класс).
 * Каждая обёрнута в namespace, чтобы не конфликтовать именами.
 * Файловый ввод-вывод симулируется (переменная fakeFs).
 */

/**
 * ============================================================
 * ШАГ 1. БЫЛО: ФАБРИЧНАЯ ФУНКЦИЯ
 * ============================================================
 * Это тот же подход, что в Задаче 5. Данные закрыты в замыкании,
 * поведение — методы возвращаемого объекта.
 */
namespace FactoryVersion {
  const fakeFs: Record<string, string> = {
    "config.json": JSON.stringify({ port: 3000, host: "localhost", debug: false }),
  };
  function readFile(path: string): string {
    return fakeFs[path];
  }
  function writeFile(path: string, content: string): void {
    fakeFs[path] = content;
  }

  type AppConfig = {
    port: number;
    host: string;
    debug: boolean;
  };

  /** Фабрика: вручную собираем замыкание и методы. */
  function createConfig(filePath: string) {
    let data: AppConfig = JSON.parse(readFile(filePath));

    return {
      getSource(): string {
        return filePath;
      },
      save(): void {
        writeFile(filePath, JSON.stringify(data));
      },
      setParam(key: string, value: any): void {
        (data as any)[key] = value;
      },
      getParam(key: string): any {
        return (data as any)[key];
      },
    };
  }

  const config = createConfig("config.json");
  config.setParam("port", 8080);
  config.save();
  console.log("[factory] port =", config.getParam("port"));
}

