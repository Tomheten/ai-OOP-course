/**
 * ============================================================
 * ЗАДАЧА 10. ИНТЕРФЕЙС NotificationSender
 * Блок 2. Первый полиморфизм
 * ============================================================
 *
 * В Задаче 9 мы увидели: у отправителей одинаковая форма (метод
 * отправки), но нет общего контракта, поэтому клиент вынужден
 * выбирать между ними через ветвление.
 *
 * Здесь мы вводим ИНТЕРФЕЙС — общий контракт отправителя — и
 * переводим систему на работу через абстракцию. Это первый
 * настоящий шаг к полиморфизму.
 *
 * ЗАДАНИЕ:
 *   - Создай интерфейс отправителя.
 *   - Переведи клиентский код на работу через этот контракт.
 *
 * Читай файл сверху вниз. Запусти его и посмотри на вывод.
 */

/**
 * ------------------------------------------------------------
 * ПРО СТРУКТУРУ ФАЙЛА И ПРО КЛЮЧЕВОЕ СЛОВО
 * ------------------------------------------------------------
 * Ниже две версии: «до интерфейса» (из Задачи 9) и «с интерфейсом».
 *
 * В этой задаче мы впервые используем ключевое слово `interface`.
 * Дальше для контрактов поведения мы будем применять именно его:
 * это инструмент, созданный для описания контракта, который
 * классы реализуют через `implements`. Это ключевое слово для подобных
 * сущностей почти во всех ООП языках. В typescript есть еще одно ключевое 
 * слово для описания контрактов - `type`
 */

/**
 * ============================================================
 * ШАГ 1. ДО ИНТЕРФЕЙСА (то, к чему пришли в Задаче 9)
 * ============================================================
 */
namespace BeforeInterface {
  /** Клиент вынужден выбирать по типу. */
  function sendNotification(type: string, to: string, message: string): void {
    if (type === "email") {
      console.log(`[EMAIL] кому=${to}: ${message}`);
    } else if (type === "sms") {
      console.log(`[SMS] кому=${to}: ${message}`);
    }
  }

  sendNotification("email", "user@example.com", "Привет");
  sendNotification("sms", "+79990000000", "Привет");
}

/**
 * ============================================================
 * ШАГ 2. ПРОВЕРКИ: ЧТО ТАКОЕ КОНТРАКТ
 * ============================================================
 */

/**
 * СИТУАЦИЯ. Что общего у всех отправителей?
 * -----------------------------------------
 * И отправитель email, и отправитель SMS делают одно и то же
 * с точки зрения клиента: ОТПРАВЛЯЮТ сообщение получателю.
 *
 * Это общее можно описать как ОБЯЗАТЕЛЬСТВО:
 *   «любой отправитель умеет отправлять: (кому, сообщение)».
 *
 * Такое обязательство и называется контрактом. В TypeScript
 * его удобно описывать через интерфейс.
 */

/**
 * ============================================================
 * ШАГ 3. С ИНТЕРФЕЙСОМ (работа через контракт)
 * ============================================================
 */
namespace WithInterface {
  /**
   * ИНТЕРФЕЙС — общий контракт отправителя уведомлений.
   * Он описывает НЕ реализацию, а обязательство:
   * любой отправитель должен уметь отправлять.
   */
  interface NotificationSender {
    send(to: string, message: string): void;
  }

  /** EmailSender обязуется выполнить контракт. */
  class EmailSender implements NotificationSender {
    send(to: string, message: string): void {
      console.log(`[EMAIL] кому=${to}: ${message}`);
    }
  }

  /** SmsSender выполняет тот же контракт. */
  class SmsSender implements NotificationSender {
    send(to: string, message: string): void {
      console.log(`[SMS] кому=${to}: ${message}`);
    }
  }

  /**
   * Клиент работает ЧЕРЕЗ КОНТРАКТ.
   * Ему не важно, какой именно отправитель передан, —
   * он знает лишь, что у того есть метод send.
   * Да, кто-то должен решить, какой отправитель создать.
   * Но это решение принимается ОДИН раз — например, в фабрике
   * или конфигурации. Весь остальной код (функция notify) уже не знает о конкретных классах
   */
  function notify(sender: NotificationSender, to: string, message: string): void {
    sender.send(to, message); // никакого выбора по типу!
  }

  notify(new EmailSender(), "user@example.com", "Привет");
  notify(new SmsSender(), "+79990000000", "Привет");
}

/**
 * ============================================================
 * ШАГ 4. ТЕ ЖЕ ПРОВЕРКИ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Клиенту больше не нужен выбор
 * Функция notify принимает NotificationSender и просто вызывает
 * send. Ей не важно, что внутри — email или sms. Ветвление исчезло.
 *
 * СИТУАЦИЯ 2. Контракт гарантирует
 * Раз класс написал `implements NotificationSender`, компилятор
 * проверит: у класса точно есть метод send с правильной сигнатурой.
 * Забыть его нельзя.
 *
 * СИТУАЦИЯ 3. Новые отправители подключаются без правки клиента
 * Чтобы добавить новый канал, достаточно создать класс,
 * реализующий интерфейс. Клиентский код (notify) менять не нужно.
 * (Подробнее проверим это в следующей задаче.)
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Открытие этой задачи:
 *   Клиент работает через контракт. Интерфейс описывает ОБЩЕЕ
 *   обязательство, а разные классы его реализуют. Клиенту не
 *   важно, кто именно перед ним, — он вызывает метод контракта.
 *
 * Это и есть базовая идея полиморфизма:
 *   разные реализации используются одинаково.
 *
 * Ситуация                | До интерфейса          | С интерфейсом
 * ------------------------|------------------------|---------------------------
 * Выбор типа в клиенте    | есть (ветвление)       | нет
 * Общий контракт          | нет                    | есть: NotificationSender
 * Новый канал             | править клиента        | клиент не меняется
 *
 * Дальше добавим ещё один способ отправки — и убедимся, что
 * клиентский код при этом трогать не придётся.
 */