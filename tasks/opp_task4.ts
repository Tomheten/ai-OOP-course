/**
 * ============================================================
 * ШАГ 1. ОТКРЫТЫЙ КОНФИГ (все знания — у вызывающего кода)
 * ============================================================
 */
namespace OpenConfig {
  /** Симуляция файловой системы. */
  const fakeFs: Record<string, string> = {
    "config.json": JSON.stringify({
      port: 3000,
      host: "localhost",
      debug: false,
      logLevel: "info",
    }),
  };

  function readFile(path: string): string {
    return fakeFs[path];
  }

  function writeFile(path: string, content: string): void {
    fakeFs[path] = content;
  }

  /**
   * Правило продукта: debug-логи (logLevel "debug") разрешены
   * ТОЛЬКО при включённом debug-режиме. Иначе продакшн тонет
   * в логах. Представь что таких правил много и в голове не удержишь,
   * нужны ограничение на уровне кода
   */

  /** Заметь: этот тип — структура хранения, и она публична.
   * Каждый, кто работает с конфигом, видит и трогает его внутренности. */
  type AppConfig = {
    port: number;
    host: string;
    debug: boolean;
    logLevel: string;
  };

  const LOG_LEVELS = ["debug", "info", "warn", "error"];

  function loadConfig(filePath: string): AppConfig {
    return JSON.parse(readFile(filePath));
  }

  /** Путь приходится передавать вручную: конфиг его не помнит. */
  function saveConfig(config: AppConfig, filePath: string): void {
    writeFile(filePath, JSON.stringify(config));
  }

  /** Проверка — как учили в Задачах 1–3: каждое поле ОТДЕЛЬНО. */
  function validateConfig(config: AppConfig): boolean {
    return (
      config.port > 0 &&
      config.port <= 65535 &&
      config.host.length > 0 &&
      LOG_LEVELS.includes(config.logLevel)
    );
  }

  /** Другая часть программы выключает debug-режим.
   * Написана другим разработчиком. Или тобой месяц спустя. */
  function disableDebugMode(config: AppConfig): void {
    config.debug = false;
    // про logLevel — забыли. Ничего не возразило.
  }

  /** Использование */
  const config = loadConfig("config.json");
  config.port = 8080;

  /** Включаем debug вручную — ДВЕ строки, которые нельзя разрывать: */
  config.debug = true;
  config.logLevel = "debug"; // забудь эту строку — и конфиг сломан

  /** ...позже другая часть программы выключает debug: */
  disableDebugMode(config);

  saveConfig(config, "config.json"); // путь снова таскаем руками

  console.log("[open] валиден?", validateConfig(config)); // true!
  console.log("[open] в файле:", readFile("config.json"));
  /** Адрес склеиваем руками — и так придётся делать в каждом месте: */
  console.log("[open] адрес:", config.host + ":" + config.port);

  /**
   * Посмотри на содержимое файла в выводе:
   *   debug: false, logLevel: "debug"
   * Debug выключен, а уровень логов остался debug.
   * В продакшне — флуд debug-логами. При этом КАЖДОЕ поле
   * по отдельности корректно, и validateConfig честно говорит true.
   */
}

