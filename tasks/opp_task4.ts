/**
 * ============================================================
 * ШАГ 3. ИНКАПСУЛИРОВАННЫЙ КОНФИГ (знания переезжают внутрь)
 * ============================================================
 * Прежде чем писать сеттеры, зададим вопрос: а что эти данные
 * ЗНАЧАТ? logLevel — не независимые данные, а следствие режима:
 * debug включён — "debug", выключен — "info".
 *
 * Значит, его вообще не нужно хранить — его можно вычислять.
 * Противоречие не нужно проверять: ему не из чего возникнуть.
 */
namespace EncapsulatedConfig {
  /** Симуляция файловой системы. */
  const fakeFs: Record<string, string> = {
    "config.json": JSON.stringify({
      port: 3000,
      host: "localhost",
      debug: false,
      logLevel: "info",
    }),
  };

  function readFile(path: string): string {
    return fakeFs[path];
  }

  function writeFile(path: string, content: string): void {
    fakeFs[path] = content;
  }

  /**
   * Фабрика создаёт конфиг. Состояние закрыто в замыкании,
   * путь конфиг помнит сам.
   */
  function createConfig(filePath: string) {
    const raw = JSON.parse(readFile(filePath));
    const host: string = raw.host;
    let port: number = raw.port;
    let debug: boolean = raw.debug;
    /** logLevel из файла НАМЕРЕННО не читаем: истина — это debug.
     * Противоречие из файла не может проникнуть внутрь. */

    /** Единственное место, где вычисляется уровень. */
    function currentLogLevel(): string {
      return debug ? "debug" : "info";
    }

    /**
     * Контракт объекта. Заметь, чего здесь НЕТ: setDebug,
     * setLogLevel, открытых полей.
     *
     * Можно было сделать setDebug + setLogLevel с проверкой пары.
     * Это была бы инкапсуляция «для галочки»: вызывающий всё так же
     * обязан помнить про пару и вызывать два метода в правильном
     * порядке. Вместо этого интерфейс говорит на языке операций
     * приложения: enableDebug / disableDebug. Состояние
     * «debug выключен, уровень debug» невыразимо.
     */
    return {
      /** Конфиг помнит, откуда он. */
      getSource(): string {
        return filePath;
      },

      /** Адрес вычисляется, а не хранится: не может разойтись с host/port. */
      getAddress(): string {
        return `${host}:${port}`;
      },

      /** Правило одного поля — как в Задачах 1–3, никуда не делось. */
      setPort(value: number): void {
        if (!Number.isInteger(value) || value <= 0 || value > 65535) {
          throw new Error("Некорректный порт: " + value);
        }
        port = value;
      },

      enableDebug(): void {
        debug = true;
      },

      disableDebug(): void {
        debug = false;
      },

      isDebug(): boolean {
        return debug;
      },

      /** Уровень — следствие режима. Сеттера уровня нет. */
      getLogLevel(): string {
        return currentLogLevel();
      },

      /** Конфиг сохраняет СЕБЯ САМ — путь уже внутри. */
      save(): void {
        writeFile(
          filePath,
          JSON.stringify({
            port,
            host,
            debug,
            logLevel: currentLogLevel(),
          })
        );
      },
    };
  }

  /** Использование: тот же сценарий, что в Шаге 1. */
  const config = createConfig("config.json");
  config.setPort(8080);
  config.enableDebug();

  /** ...позже другая часть программы выключает debug: */
  config.disableDebug(); // «забыть» уровень невозможно: он не хранится

  config.save(); // путь передавать НЕ нужно

  console.log("[object] в файле:", readFile("config.json"));
  console.log("[object] адрес:", config.getAddress());
  console.log("[object] уровень:", config.getLogLevel());
  console.log("[object] источник:", config.getSource());

  /**
   * Сравни две строки «в файле» из Шага 1 и отсюда:
   * всё одинаково, кроме уровня. Вся разница — в этом уровне.
   *
   * Выразить сломанное состояние нельзя:
   */
  // config.debug = false;        // ❌ нет такого поля
  // config.logLevel = "debug";   // ❌ нет такого поля
  // config.setLogLevel("debug"); // ❌ нет такого метода: уровень не задаётся напрямую
}

/**
 * ============================================================
 * ШАГ 4. ТЕ ЖЕ ПРОВЕРКИ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Противоречие невыразимо
 * Проверку пары мы НЕ написали — она не нужна. Уровень вычисляется
 * из режима, отдельных данных для него нет. Конфиг корректен в
 * любой момент, включая момент загрузки. Лучшая проверка — та,
 * которая не нужна. Правила отдельных полей (порт) при этом
 * остались — ровно как в Задачах 1–3.
 *
 * СИТУАЦИЯ 2. Знания переехали внутрь
 * Вызывающий код знает только контракт: setPort, enableDebug,
 * disableDebug, save, getAddress. Путь — внутри. Адрес — внутри.
 * Уровень — следствие. Новому разработчику нечего забывать:
 * дисциплина заменилась гарантией.
 *
 * СИТУАЦИЯ 3. Смени формат хранения — посчитай снова
 * logLevel числом в файле? Меняется ОДНО место внутри save()
 * (плюс константа соответствия). Контракт getLogLevel(): string
 * не двигается. Код использования — НОЛЬ изменённых строк.
 * Сравни со своим счётом из Шага 2.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Задачи 1–3 отвечали «как»: спрячь поля, правило — в одном месте.
 * Эта задача отвечает «зачем»: инкапсуляция — это ГРАНИЦА ЗНАНИЯ.
 * Объект скрывает не столько данные, сколько решения:
 * что от чего зависит, как оно хранится, откуда оно пришло.
 * Всё, что не скрыто, становится чужой обязанностью.
 *
 * Две выплаты по этой границе:
 *   1. Некорректное состояние не «отлавливается» — оно невыразимо.
 *   2. Внутренности можно менять, не ломая внешний код.
 *      Код живёт годами, требования меняются — инкапсуляция
 *      покупается ради изменений.
 *
 * И ловушка: геттеры/сеттеры на каждое поле — не инкапсуляция.
 * Это те же открытые знания, только с новым синтаксисом.
 * Интерфейс должен говорить на языке операций (enableDebug),
 * а не на языке полей (setDebug).
 *
 * Знание                  | Открытый конфиг          | Инкапсулированный
 * ------------------------|--------------------------|---------------------------
 * debug и logLevel — пара | помнит каждый вызывающий | уровень вычисляется
 * Путь к файлу            | таскают вручную          | внутри, config.save()
 * Как собрать адрес       | склеивают в каждом месте | config.getAddress()
 * Формат хранения         | знают все, кто трогал поля| только внутренности
 *
 * Конфиг научился отвечать за себя. В следующей задаче он обрастёт
 * новыми требованиями — validate, reset, export, clone — и мы
 * увидим, что происходит, когда вокруг объекта снова собирается
 * целый кластер функций.
 */