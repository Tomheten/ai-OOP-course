/**
 * СИТУАЦИЯ 1. Объект не помнит, откуда он
 * ---------------------------------------
 * Загрузили конфиг из "config.json". А чтобы СОХРАНИТЬ, нужно
 * СНОВА передать путь:
 *
 *   saveConfig(config, "config.json");
 *
 * Сам конфиг не знает, из какого файла он пришёл. Это знание
 * живёт не в объекте, а в голове вызывающего кода.
 *
 * А если у тебя ДВА конфига из разных файлов? Придётся вручную
 * помнить, какой путь к какому конфигу относится.
 */

/**
 * СИТУАЦИЯ 2. Объект не умеет себя сохранять
 * ------------------------------------------
 * У конфига нет способа сохранить себя. Каждый раз вызывающий
 * код должен знать: «ага, для сохранения нужна функция
 * saveConfig и путь». Объект сам об этом не знает.
 */

/**
 * СИТУАЦИЯ 3. Правила не живут в объекте. Если они вообще есть — они где-то снаружи, в коде вызывающего.
 * ----------------------------------------
 * Можно записать что угодно:
 *   config.port = -1;
 *   config.logLevel = "banana";
 * Объект не понимает, что это некорректные значения.
 * Правила живут где-то снаружи (если вообще живут).
 */

/**
 * ПАУЗА. СФОРМУЛИРУЙ ДЛЯ СЕБЯ
 * ---------------------------
 *   1. Знает ли конфиг, из какого файла он загружен?
 *   2. Может ли конфиг сохранить себя сам?
 *   3. Кто отвечает за корректность значений — объект или код вокруг?
 *
 * Объект существует, но ничего не знает о себе.
 */

/**
 * ============================================================
 * ШАГ 3. ОБЪЕКТ + МЕТОДЫ (объект узнаёт о себе)
 * ============================================================
 * Конфигурация теперь помнит свой источник и умеет сама
 * загружаться, сохраниться и менять параметры.
 */
namespace ConfigWithMethods {
  /** Симуляция файловой системы. */
  const fakeFs: Record<string, string> = {
    "config.json": JSON.stringify({
      port: 3000,
      host: "localhost",
      debug: false,
      logLevel: "info",
    }),
  };

  function readFile(path: string): string {
    return fakeFs[path];
  }

  function writeFile(path: string, content: string): void {
    fakeFs[path] = content;
  }

  /** Допустимые уровни логирования. */
  const LOG_LEVELS = ["debug", "info", "warn", "error"];

  /**
   * Фабрика создаёт конфигурацию и сразу знает, из какого она файла.
   * Состояние закрыто в замыкании.
   */
  function createConfig(filePath: string) {
    /** Загружаем данные при создании. */
    let data = JSON.parse(readFile(filePath));

    /** Одна точка изменения порта — здесь живёт правило. */
    function setPortInterval(value: number): void {
      if (value <= 0 || value > 65535) {
        throw new Error("Некорректный порт: " + value);
      }
      data.port = value;
    }

    /** Одна точка изменения уровня логирования. */
    function setLogLevel(value: string): void {
      if (!LOG_LEVELS.includes(value)) {
        throw new Error("Некорректный уровень логирования: " + value);
      }
      data.logLevel = value;
    }

    return {
      /** Конфиг помнит, откуда он. */
      getSource(): string {
        return filePath;
      },

      /** Конфиг сохраняет СЕБЯ САМ — путь уже внутри. */
      save(): void {
        writeFile(filePath, JSON.stringify(data));
      },

      setPort(value: number): void {
        setPortInterval(value);
      },

      setLogLevel(value: string): void {
        setLogLevel(value);
      },

      getParam(key: string): any {
        return (data as any)[key];
      },
    };
  }

  /** Использование: конфиг знает о себе. */
  const config = createConfig("config.json");
  config.setPort(8080);
  config.save(); // путь передавать НЕ нужно — конфиг его помнит
  console.log("[config+methods] источник =", config.getSource());
  console.log("[config+methods] port =", config.getParam("port"));

  /**
   * Сломать не получится:
   */
  // config.setPort(-1);          // ❌ бросит ошибку
  // config.setLogLevel("banana"); // ❌ бросит ошибку
}

/**
 * ============================================================
 * ШАГ 4. ТЕ ЖЕ ПРОВЕРКИ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Объект помнит источник
 * Путь к файлу сохранён внутри фабрики. Чтобы сохранить конфиг,
 * больше не нужно ничего передавать: config.save().
 *
 * СИТУАЦИЯ 2. Объект умеет себя сохранять
 * Сохранение — это метод самого конфига. Вызывающему коду не
 * нужно знать про отдельную функцию и путь.
 *
 * СИТУАЦИЯ 3. Объект знает свои правила
 * Порт и уровень логирования проверяются в одном месте.
 * Записать некорректное значение нельзя — объект сопротивляется.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Главный вывод этой задачи:
 *   Объект может «знать о себе» — помнить источник, уметь
 *   сохраняться, проверять свои значения. Когда поведение
 *   группируется вокруг данных, вызывающему коду становится
 *   проще: он общается с объектом, а не жонглирует функциями
 *   и аргументами.
 *
 * Ситуация                | Объект + функции        | Объект + методы
 * ------------------------|-------------------------|---------------------------
 * Помнит источник         | нет, путь передают      | да, внутри
 * Сохранить себя          | нет, нужна функция+путь | да, config.save()
 * Правила значений        | снаружи (или их нет)    | внутри объекта
 *
 * Дальше добавим вокруг конфига ещё больше функций и увидим,
 * во что это превращается.
 */