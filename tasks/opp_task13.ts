namespace TodoGoalPreview {
  /** Данные и поведение вместе. Это ориентир, а не задание. */
  function createTodo(title: string) {
    let completed = false;

    return {
      complete(): void {
        completed = true;
      },
      reopen(): void {
        completed = false;
      },
      isCompleted(): boolean {
        return completed;
      },
    };
  }

  const todo = createTodo("Купить молоко");
  todo.complete();
  console.log("[todo-goal-preview] выполнено:", todo.isCompleted());
}

