/**
 * СИТУАЦИЯ 1. Метод можно обойти
 * ------------------------------
 * Раз поле открыто, любой код меняет его напрямую. Тогда зачем
 * нужен метод? Он не является единственной точкой изменения.
 */

/**
 * СИТУАЦИЯ 2. Невозможно найти виновного
 * ---------------------------------------
 * Если статус вдруг стал некорректным, искать причину бесполезно:
 * поменять поле мог кто угодно и где угодно.
 */

/**
 * ============================================================
 * ШАГ 3. СОСТОЯНИЕ ЗАЩИЩЕНО
 * ============================================================
 * Делаем поля приватными. Единственный путь к состоянию — методы.
 */
namespace StateProtected {
  type TodoStatus = "active" | "completed";

  class Todo {
    private title: string;
    private status: TodoStatus; // теперь приватное

    constructor(title: string) {
      this.title = title;
      this.status = "active";
    }

    complete(): void {
      this.status = "completed";
    }

    reopen(): void {
      this.status = "active";
    }

    /** Для чтения даём отдельный метод. */
    getStatus(): TodoStatus {
      return this.status;
    }

    getTitle(): string {
      return this.title;
    }
  }

  const todo = new Todo("Купить молоко");
  todo.complete();
  console.log("[protected] статус:", todo.getStatus());

  /** Обойти методы больше нельзя. */
  // todo.status = "active";  // ❌ Property 'status' is private
  // todo.title = "";         // ❌ Property 'title' is private
}

/**
 * ============================================================
 * ШАГ 4. СРАВНЕНИЕ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Единственная точка изменения
 * В защищённой версии состояние меняется ТОЛЬКО через методы.
 * Методы становятся настоящими «дверями» в состояние объекта.
 *
 * СИТУАЦИЯ 2. Причина всегда найдётся
 * Если статус изменился — это сделал один из методов. Искать
 * нужно только там.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Мы запретили прямое изменение состояния. Теперь:
 *   - поля приватные;
 *   - единственный путь к ним — методы;
 *   - объект контролирует, как меняется его состояние.
 *
 * Ситуация            | Состояние открыто     | Состояние защищено
 * --------------------|-----------------------|---------------------------
 * Изменить в обход    | можно                 | нельзя
 * Метод — точка входа | нет                   | да
 * Поиск причины бага  | по всему коду         | в методах объекта
 *
 * Но методы пока ничего не проверяют: можно «завершить» уже
 * завершённую задачу. Допустимые переходы добавим дальше.
 */