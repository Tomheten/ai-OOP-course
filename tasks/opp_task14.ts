/**
 * СИТУАЦИЯ 1. Действия живут отдельно
 * ----------------------------------
 * completeTodo, reopenTodo, renameTodo принимают Todo аргументом.
 * Сам Todo не делает ничего. Поведение — снаружи, как в Блоке 1.
 */

/**
 * СИТУАЦИЯ 2. Никто не мешает делать что угодно
 * ---------------------------------------------
 * Можно «завершить» уже завершённую задачу. Можно переименовать
 * в пустую строку. Функции ничего не проверяют — правил нет,
 * а состояние открыто.
 */

/**
 * СИТУАЦИЯ 3. Кто умеет работать с Todo?
 * --------------------------------------
 * Чтобы понять, что можно сделать с Todo, нужно искать функции
 * по файлу. Сам Todo молчит.
 */

/**
 * ============================================================
 * ШАГ 3. ВЗГЛЯД НА ЦЕЛЬ: ДЕЙСТВИЯ ВНУТРИ
 * ============================================================
 */
namespace TodoWithMethodsPreview {
  function createTodo(initialTitle: string) {
    let completed = false;
    let title = initialTitle;

    return {
      complete(): void {
        completed = true;
      },
      reopen(): void {
        completed = false;
      },
      rename(newTitle: string): void {
        title = newTitle;
      },
      getTitle(): string {
        return title;
      },
      isCompleted(): boolean {
        return completed;
      },
    };
  }

  const todo = createTodo("Купить молоко");
  todo.complete();
  todo.rename("Купить молоко и хлеб");
  console.log("[todo+methods]", todo.getTitle(), todo.isCompleted());
}

/**
============================================================
ШАГ 4. ТЕ ЖЕ ПРОВЕРКИ
============================================================
СИТУАЦИЯ 1. Действия переехали
Теперь Todo ДЕЙСТВУЕТ САМ: todo.complete(), todo.rename(...).
Его не передают в функции — он сам знает, как себя менять.
Поведение переехало внутрь.
СИТУАЦИЯ 2. Объект защищает данные
Состояние закрыто в замыкании фабрики. Снаружи нельзя написать
todo.completed = true — такого поля просто нет. Переименовать
в пустую строку тоже не получится, если добавить проверку в
единственную точку изменения.
СИТУАЦИЯ 3. Todo подсказывает свои возможности
Открой объект, который возвращает фабрика, и ты сразу видишь:
complete, reopen, rename, getTitle, isCompleted. Вот всё,
что можно сделать. Искать функции по файлу больше не нужно.
*/
