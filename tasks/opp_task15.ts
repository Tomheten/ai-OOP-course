/**
 * СИТУАЦИЯ 1. Правила дублируются
 * -------------------------------
 * Посмотри: и completeTodo, и renameTodo проверяют
 * `status !== "active"`. Одна и та же проверка в разных местах.
 * Добавь третье действие для активной задачи — проверка
 * скопируется ещё раз.
 */

/**
 * СИТУАЦИЯ 2. Правила живут в функциях, а не в Todo
 * -------------------------------------------------
 * Сам Todo не знает своего жизненного цикла. Правила — это
 * проверки внутри функций. Если кто-то поменяет поле напрямую
 * (оно ведь открыто), правило не сработает.
 */

/**
 * СИТУАЦИЯ 3. Что будет при росте числа состояний?
 * ------------------------------------------------
 * Если состояний станет три-четыре, проверки запутаются.
 * Каждой функции нужно знать, из каких состояний она допустима.
 * Это знание размазано по функциям.
 */

/**
 * ============================================================
 * ШАГ 3. ВЗГЛЯД НА ЦЕЛЬ: ПЕРЕХОДЫ В ОДНОМ МЕСТЕ
 * ============================================================
 */
namespace TodoLifecyclePreview {
  type TodoStatus = "active" | "completed";

  function createTodo(initialTitle: string) {
    let status: TodoStatus = "active";

    /** Одно место, которое знает про переходы. */
    function transition(from: TodoStatus, to: TodoStatus): void {
      if (status !== from) {
        throw new Error(`Нельзя перейти в ${to} из состояния ${status}`);
      }
      status = to;
    }

    return {
      complete(): void {
        transition("active", "completed");
      },
      reopen(): void {
        transition("completed", "active");
      },
      getStatus(): TodoStatus {
        return status;
      },
    };
  }

  const todo = createTodo("Купить молоко");
  todo.complete();
  console.log("[lifecycle+methods] статус:", todo.getStatus());
}

/**
* ============================================================
* ШАГ 4. ТЕ ЖЕ ПРОВЕРКИ
* ============================================================
* СИТУАЦИЯ 1. Правило в одном месте
* Вся логика переходов живёт в ОДНОЙ функции — `transition`.
* И `complete`, и `reopen` используют её. Проверка больше не
* дублируется. Если правило изменится — правим одно место.
* СИТУАЦИЯ 2. Сломать нельзя
* Состояние закрыто в замыкании фабрики. Снаружи нельзя написать
* todo.status = "completed" — такого поля просто нет. Переход
* в неверное состояние невозможен: `transition` проверит.
* СИТУАЦИЯ 3. Новое состояние — одна правка
* Если появится третье состояние (например, "archived"), нужно
* добавить переход в `transition`. Все действия, которые
* используют переход, получат проверку автоматически. Знание
* о жизненном цикле сосредоточено в одном месте.
*/

/**
* ============================================================
* ИТОГ
* ============================================================
* Главный вывод этой задачи:
* Когда у объекта появляются состояния и правила переходов,
* держать проверки в каждой функции — значит дублировать знание.
* Жизненный цикл должен жить в одном месте внутри объекта.
* Ситуация               | Правила в функциях      | Правила в объекте
* Проверка перехода      | в каждой функции        | одна функция перехода
* Новое действие         | копировать проверку     | использовать переход
* Знание о цикле         | размазано по функциям   | сосредоточено в одном месте
* Сломать состояние      | легко, поле открыто     | нельзя, замыкание
* Дальше начнём переносить действия и правила внутрь Todo —
* и увидим, как объект становится единственным владельцем
* своего жизненного цикла.
*/