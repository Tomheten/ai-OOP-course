/**
 * ============================================================
 * ШАГ 1. СОСТОЯНИЯ + ПРАВИЛА В ФУНКЦИЯХ
 * ============================================================
 */
namespace TodoLifecycleFunctions {
  /** У Todo два состояния. */
  type TodoStatus = "active" | "completed";

  type Todo = {
    id: number;
    title: string;
    status: TodoStatus;
    createdAt: string;
  };

  let nextId = 1;

  function createTodo(title: string): Todo {
    return {
      id: nextId++,
      title,
      status: "active",
      createdAt: new Date().toISOString(),
    };
  }

  /** Завершить можно только активную задачу. */
  function completeTodo(todo: Todo): void {
    if (todo.status !== "active") {
      throw new Error("Завершить можно только активную задачу");
    }
    todo.status = "completed";
  }

  /** Переоткрыть можно только завершённую задачу. */
  function reopenTodo(todo: Todo): void {
    if (todo.status !== "completed") {
      throw new Error("Переоткрыть можно только завершённую задачу");
    }
    todo.status = "active";
  }

  /** Переименовать можно только активную задачу. */
  function renameTodo(todo: Todo, newTitle: string): void {
    if (todo.status !== "active") {
      throw new Error("Переименовать можно только активную задачу");
    }
    todo.title = newTitle;
  }

  const todo = createTodo("Купить молоко");
  completeTodo(todo);
  console.log("[lifecycle+functions] статус:", todo.status);

  /** Раскомментируй — функция защитит правило: */
  // completeTodo(todo); // ❌ уже завершена
}

