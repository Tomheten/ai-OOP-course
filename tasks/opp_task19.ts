/**
 * ============================================================
 * ЗАДАЧА 19. КТО ОТВЕЧАЕТ ЗА ПРАВИЛО?
 * Блок 3. Ответственность объекта
 * ============================================================
 *
 * Мы умеем защищать состояние и инварианты. Теперь главный
 * вопрос блока: КТО ДОЛЖЕН ЗНАТЬ БИЗНЕС-ПРАВИЛО?
 *
 * Есть два варианта:
 *   - правило знает внешний сервис, а объект — только данные;
 *   - правило знает сам объект.
 *
 * Сравним их и сделаем вывод.
 * В Задаче 18 мы поместили правила переходов в объект. 
 * Но в реальном коде часто делают иначе — правило живёт в сервисе, 
 * а объект остаётся только данными. Сравним оба подхода
 *
 * ЗАДАНИЕ:
 *   - Определи, где должно жить бизнес-правило.
 *
 * Читай файл сверху вниз. Запусти его и посмотри на вывод.
 */

/**
 * ============================================================
 * ШАГ 1. ПРАВИЛО В СЕРВИСЕ (объект — только данные)
 * ============================================================
 */
namespace RuleInService {
  type TodoStatus = "active" | "completed";

  /** Анемичный Todo: только данные, правил не знает. */
  class Todo {
    title: string;
    status: TodoStatus;

    constructor(title: string) {
      this.title = title;
      this.status = "active";
    }
  }

  /** Сервис знает бизнес-правило ВМЕСТО объекта. */
  class TodoService {
    complete(todo: Todo): void {
      // правило живёт здесь, а не в Todo
      if (todo.status !== "active") {
        throw new Error("Завершить можно только активную задачу");
      }
      todo.status = "completed";
    }
  }

  const todo = new Todo("Купить молоко");
  const service = new TodoService();
  service.complete(todo);
  console.log("[rule-in-service] статус:", todo.status);

  /** Но сам Todo ничего не знает о правиле. */
  todo.status = "completed"; // можно поменять в обход сервиса и правила
}

/**
 * ============================================================
 * ШАГ 2. ПРОВЕРКИ: ГДЕ ДОЛЖНО ЖИТЬ ПРАВИЛО
 * ============================================================
 */

/**
 * СИТУАЦИЯ 1. Правило оторвано от данных
 * ---------------------------------------
 * В Шаге 1 правило «завершить можно только активную» знает сервис.
 * Но данные, которые это правило защищает, — в Todo. Правило и
 * данные живут в разных местах.
 */

/**
 * СИТУАЦИЯ 2. Правило легко обойти
 * --------------------------------
 * Раз правило в сервисе, любой код может поменять todo.status
 * напрямую — в обход сервиса. Правило защищает данные только
 * тогда, когда все ходят через сервис. А это ничто не гарантирует.
 */

/**
 * СИТУАЦИЯ 3. Правило может продублироваться
 * ------------------------------------------
 * Появится второй сервис, которому тоже нужно «завершать» задачи, —
 * и ему придётся заново знать и проверять то же правило. Правило
 * начнёт расползаться по сервисам.
 */

/**
 * СИТУАЦИЯ 4. Главный вопрос
 * --------------------------
 * Кому принадлежит правило «завершить можно только активную
 * задачу»? Это правило ПРО СОСТОЯНИЕ TODO. Значит, знать его
 * должен тот, кто владеет этим состоянием, — сам Todo.
 */

/**
 * ============================================================
 * ШАГ 3. ПРАВИЛО В ОБЪЕКТЕ (объект отвечает за себя)
 * ============================================================
 */
namespace RuleInObject {
  type TodoStatus = "active" | "completed";

  /** Rich Todo: знает своё бизнес-правило. */
  class Todo {
    private title: string;
    private status: TodoStatus;

    constructor(title: string) {
      this.title = title;
      this.status = "active";
    }

    complete(): void {
      // правило живёт ВМЕСТЕ с данными, которые защищает
      if (this.status !== "active") {
        throw new Error("Завершить можно только активную задачу");
      }
      this.status = "completed";
    }

    getStatus(): TodoStatus {
      return this.status;
    }
  }

  const todo = new Todo("Купить молоко");
  todo.complete();
  console.log("[rule-in-object] статус:", todo.getStatus());

  /** Обойти правило нельзя: оно внутри, а состояние закрыто. */
  // todo.status = "completed"; // ❌ поле приватное
}

/**
 * ============================================================
 * ШАГ 4. СРАВНЕНИЕ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Правило рядом с данными
 * В версии с объектом правило живёт там же, где данные, которые
 * оно защищает. Их невозможно разделить.
 *
 * СИТУАЦИЯ 2. Правило нельзя обойти
 * Состояние закрыто, а единственный путь к нему — метод с правилом.
 *
 * СИТУАЦИЯ 3. Правило не дублируется
 * Всем, кому нужно «завершить задачу», достаточно вызвать
 * todo.complete(). Правило применится само.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Главный вопрос: кто должен знать бизнес-правило?
 * Ответ: тот, кто владеет данными, которые это правило защищает.
 *
 * Если правило про состояние Todo — его должен знать Todo.
 *
 * Ситуация           | Правило в сервисе      | Правило в объекте
 * -------------------|------------------------|---------------------------
 * Правило и данные   | в разных местах        | вместе
 * Обойти правило     | можно                  | нельзя
 * Дублирование       | по сервисам            | нет
 *
 * Вариант «правило в сервисе, объект — только данные» называется
 * АНЕМИЧНОЙ моделью. В следующем блоке мы разберём, почему это
 * проблема, и как прийти к богатой (rich) модели.
 */