/**
 * СИТУАЦИЯ 1. Добавь push-уведомление
 * -----------------------------------
 * Чтобы добавить третий тип, нужно СНОВА лезть в тело функции
 * и дописывать ветку:
 *
 *   } else if (type === "push") { ... }
 *
 * Каждый новый тип = правка существующего кода. А если таких
 * функций несколько (в разных местах системы), править придётся
 * каждую.
 */

/**
 * СИТУАЦИЯ 2. Дублирование структуры
 * ----------------------------------
 * Посмотри на ветки для email и sms. Они ПОЧТИ одинаковые:
 * получить получателя, отправить сообщение. Отличается только
 * «как именно отправить». Структура дублируется.
 */

/**
 * СИТУАЦИЯ 3. Условная логика расползается
 * ----------------------------------------
 * Один switch здесь — полбеды. Но в реальном приложении выбор
 * «это email или sms?» понадобится и при отправке, и при
 * логировании, и при повторе неудачных отправок. Условная логика
 * начнёт расползаться по всей системе.
 */

/**
 * ============================================================
 * ШАГ 3. ОБЪЕКТЫ ЕСТЬ, НО КЛИЕНТ ВСЁ РАВНО ВЫБИРАЕТ
 * ============================================================
 * Даже если разнести отправку по классам, без общего контракта
 * клиент всё равно вынужден выбирать, какой класс использовать.
 * Клиент знает про ОБА класса. Если появится третий — придётся править 
 * и эту функцию. Знание о конкретных классах расползается
 */
namespace SendersButSwitching {
  class EmailSender {
    send(to: string, message: string): void {
      console.log(`[EMAIL] кому=${to}: ${message}`);
    }
  }

  class SmsSender {
    send(to: string, message: string): void {
      console.log(`[SMS] кому=${to}: ${message}`);
    }
  }

  /** Объекты есть, но клиент всё равно решает через ветвление. */
  function notify(type: string, to: string, message: string): void {
    if (type === "email") {
      new EmailSender().send(to, message);
    } else if (type === "sms") {
      new SmsSender().send(to, message);
    }
  }

  notify("email", "user@example.com", "Привет");
  notify("sms", "+79990000000", "Привет");
}

/**
 * ============================================================
 * ШАГ 4. ЧТО ПОКАЗАЛИ ОБЕ ВЕРСИИ
 * ============================================================
 *
 * СИТУАЦИЯ 1. В обеих версиях есть выбор по типу
 * И в функции со switch, и в версии с классами клиент вынужден
 * решать «это email или sms?». Ветвление никуда не делось.
 *
 * СИТУАЦИЯ 2. У отправителей одинаковая форма, но нет общего имени
 * И у EmailSender, и у SmsSender есть метод send. Но это просто
 * совпадение: у классов НЕТ общего контракта, поэтому клиент не
 * может работать с ними одинаково — ему приходится выбирать.
 *
 * СИТУАЦИЯ 3. Чего не хватает
 * Не хватает ОДНОГО общего типа, которым можно было бы назвать
 * и EmailSender, и SmsSender. Тогда клиент принимал бы этот тип
 * и просто вызывал send — без всякого выбора.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Открытие этой задачи:
 *   Появляется дублирование структуры кода и условная логика.
 *   Каждый новый тип уведомления требует править ветвление.
 *   У похожих объектов нет общего контракта, поэтому клиент
 *   вынужден выбирать между ними вручную.
 *
 * Ситуация                | Одна функция со switch | Классы без контракта
 * ------------------------|------------------------|---------------------------
 * Выбор типа              | внутри функции         | в клиенте
 * Новый тип               | править ветвление      | править выбор в клиенте
 * Общий контракт          | нет                    | нет
 *
 * Дальше введём общий контракт — интерфейс — и уберём выбор
 * из клиентского кода.
 */