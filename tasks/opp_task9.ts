/**
 * ============================================================
 * ШАГ 1. ОДНА ФУНКЦИЯ СО SWITCH
 * ============================================================
 * Самый наивный вариант: одна функция, внутри выбор по типу.
 */
namespace SwitchVersion {
  /** Одна функция на все типы. Внутри ветвление. */
  function sendNotification(type: string, to: string, message: string): void {
    if (type === "email") {
      console.log(`[EMAIL] кому=${to}: ${message}`);
    } else if (type === "sms") {
      console.log(`[SMS] кому=${to}: ${message}`);
    } else {
      throw new Error("Неизвестный тип уведомления: " + type);
    }
  }

  sendNotification("email", "user@example.com", "Привет");
  sendNotification("sms", "+79990000000", "Привет");
}

