/**
 * ------------------------------------------------------------
 * ПРО СТРУКТУРУ ФАЙЛА
 * ------------------------------------------------------------
 * Ниже две версии: «объект + функции» и «объект + методы».
 * Чтобы они не конфликтовали именами, каждая обёрнута в namespace.
 * Не заостряй внимание на namespace — это просто контейнеры.
 */

/**
 * ============================================================
 * ШАГ 1. ОБЪЕКТ + ФУНКЦИИ
 * ============================================================
 * Объект настроек существует, но все действия с ним — функции,
 * которые принимают настройки первым аргументом.
 */
namespace SettingsPlusFunctions {
  /** Настройки — объект только с данными. */
  type AppSettings = {
    theme: string;
    language: string;
    fontSize: number;
    autosave: boolean;
  };

  function createSettings(): AppSettings {
    return {
      theme: "light",
      language: "ru",
      fontSize: 14,
      autosave: true,
    };
  }

  /** Каждая функция принимает настройки ПЕРВЫМ аргументом. */
  function setTheme(settings: AppSettings, theme: string): void {
    settings.theme = theme;
  }

  function setLanguage(settings: AppSettings, language: string): void {
    settings.language = language;
  }

  function setFontSize(settings: AppSettings, size: number): void {
    settings.fontSize = size;
  }

  function toggleAutosave(settings: AppSettings): void {
    settings.autosave = !settings.autosave;
  }

  /** В браузере здесь был бы реальный рендеринг. */
  function applySettings(settings: AppSettings): void {
    console.log("Применяем настройки:", settings);
  }

  function getSettingsSummary(settings: AppSettings): string {
    return `Тема: ${settings.theme}, язык: ${settings.language}, шрифт: ${settings.fontSize}`;
  }

  /** Использование */
  const settings = createSettings();
  setTheme(settings, "dark");
  setFontSize(settings, 16);
  toggleAutosave(settings);
  applySettings(settings);
  console.log("[settings+functions]", getSettingsSummary(settings));

  /**
   * СИТУАЦИЯ (попробуй сам): раскомментируй — настройки не защищены.
   */
  // settings.fontSize = -100;   // получается!
  // settings.theme = "";        // получается!
  // console.log("[settings+functions] Сломано:", settings);
}

