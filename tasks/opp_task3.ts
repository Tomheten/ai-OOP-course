/**
 * ============================================================
 * ШАГ 3. ОБЪЕКТ + МЕТОДЫ
 * ============================================================
 * Функции, которые тесно связаны с настройками, переезжают
 * внутрь. Объект с методами создаёт фабричная функция.
 */
namespace SettingsWithMethods {
  /**
   * Фабрика создаёт настройки и сразу даёт им поведение.
   * Состояние закрыто в замыкании.
   */
  function createSettings() {
    let theme = "light";
    let language = "ru";
    let fontSize = 14;
    let autosave = true;

    /** Одна точка установки размера шрифта — здесь живёт правило. */
    function setFontSizeInternal(size: number): void {
      if (size <= 0) {
        throw new Error("Размер шрифта должен быть положительным");
      }
      fontSize = size;
    }

    return {
      setTheme(value: string): void {
        theme = value;
      },

      setLanguage(value: string): void {
        language = value;
      },

      setFontSize(size: number): void {
        setFontSizeInternal(size);
      },

      toggleAutosave(): void {
        autosave = !autosave;
      },

      /** В браузере здесь был бы реальный рендеринг.
       * this здесь — сам объект настроек. this.getSummary() вызывает соседний метод.
       * 
       */
      apply(): void {
        console.log("Применяем настройки:", this.getSummary());
      },

      getSummary(): string {
        return `Тема: ${theme}, язык: ${language}, шрифт: ${fontSize}`;
      },
    };
  }

  /** Использование: настройки ДЕЙСТВУЮТ САМИ. */
  const settings = createSettings();
  settings.setTheme("dark");
  settings.setFontSize(16);
  settings.toggleAutosave();
  settings.apply();
  console.log("[settings+methods]", settings.getSummary());

  /**
   * Сломать не получится:
   */
  // settings.fontSize = -100;   // ❌ нет такого поля снаружи
}

/**
 * ============================================================
 * ШАГ 4. ТЕ ЖЕ ПРОВЕРКИ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Функции переехали
 * Шесть «приклеенных» функций стали методами объекта.
 * Они больше не болтаются в файле — они принадлежат настройкам.
 *
 * СИТУАЦИЯ 2. Новая настройка — новый метод
 * Нужна контрастность? Добавляешь метод внутрь объекта.
 * Всё, что относится к настройкам, остаётся в одном месте.
 *
 * СИТУАЦИЯ 3. Поведение принадлежит объекту
 * Открой объект, который возвращает фабрика, — ты сразу видишь
 * все его возможности: setTheme, setFontSize, toggleAutosave...
 *
 * СИТУАЦИЯ 4. Настройки защищены
 * Состояние закрыто в замыкании. Правило «размер шрифта > 0»
 * проверяется в одном месте — в setFontSizeInternal.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Главный вывод этой задачи:
 *   Некоторые функции настолько тесно связаны с конкретным
 *   объектом, что должны быть ЕГО методами. Когда таких функций
 *   становится много, они образуют «кучу» вокруг объекта —
 *   и эту кучу пора переселять внутрь.
 * 
 * Группу функций, связанных с одним объектом, называют кластером поведения. 
 * Этот кластер пора сделать методами объекта.
 *
 * Ситуация               | Объект + функции        | Объект + методы
 * -----------------------|-------------------------|---------------------------
 * Действия с настройками | функции в файле         | методы объекта
 * Новая настройка        | новая функция в куче    | новый метод внутри
 * «Что можно сделать?»   | искать по файлу         | видно по объекту
 * Защита значений        | нет, поля открыты       | есть, замыкание
 *
 * Дальше перенесём ту же идею на конфигурацию серверного
 * приложения — и увидим, что объект может «знать о себе» больше.
 */