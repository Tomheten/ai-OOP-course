/**
 * ============================================================
 * ЗАДАЧА 2. Объект заметки: достаточно ли просто собрать данные?
 * Блок 1. От функций к объектам
 * ============================================================
 *
 * В Задаче 1 мы увидели: когда данные и поведение разделены,
 * код начинает трещать. Естественная мысль — «соберу данные
 * заметки в одно место». Так появляется объект заметки.
 *
 * Но достаточно ли просто собрать данные в объект?
 *
 * В этой задаче ты сделаешь первый шаг: создашь объект заметки,
 * НО продолжишь использовать функции вокруг него. И увидишь,
 * что проблема никуда не делась — она просто изменила форму.
 *
 * ЗАДАНИЕ:
 *   - Создай единый объект заметки (все данные вместе).
 *   - Продолжай работать с ним через отдельные функции.
 *
 * Читай файл сверху вниз. Запусти его и посмотри на вывод.
 */

/**
 * ------------------------------------------------------------
 * ПРО СТРУКТУРУ ФАЙЛА
 * ------------------------------------------------------------
 * Ниже две версии: «объект + функции» и «объект + методы».
 * Чтобы они не конфликтовали именами, каждая обёрнута в namespace.
 * Не заостряй внимание на namespace — это просто контейнеры.
 */

/**
 * ============================================================
 * ШАГ 1. ОБЪЕКТ + ФУНКЦИИ (поведение всё ещё снаружи)
 * ============================================================
 * Мы собрали данные заметки в один объект. Это уже лучше, чем
 * разрозненные поля. Но поведение осталось в функциях.
 */
namespace ObjectPlusFunctions {
  /** Заметка — объект, но только с данными. */
  type Note = {
    id: number;
    title: string;
    content: string;
    tags: string[];
    isPinned: boolean;
  };

  /** Фабрика создаёт объект заметки. Только данные. */
  function createNote(id: number, title: string, content: string, tags: string[]): Note {
    return {
      id,
      title,
      content,
      tags: [...tags],
      isPinned: false,
    };
  }

  /** Поведение — отдельные функции. Заметка передаётся ПАРАМЕТРОМ.
  * Функция меняет чужой объект. Заметка не контролирует, что с ней делают
  */
  function renameNote(note: Note, newTitle: string): void {
    note.title = newTitle;
  }

  function addTagToNote(note: Note, tag: string): void {
    if (!note.tags.includes(tag)) {
      note.tags.push(tag);
    }
  }

  function pinNote(note: Note): void {
    note.isPinned = true;
  }

  /** Использование: заметка — пассивный «пассажир» в функциях. */
  const note = createNote(1, "Идеи проекта", "Сделать менеджер задач", ["работа"]);
  renameNote(note, "Идеи для нового проекта"); // заметку ПЕРЕДАЁМ в функцию
  addTagToNote(note, "важное");
  pinNote(note);

  console.log("[object+functions] Заметка:", note);

  /**
   * СИТУАЦИЯ 2 (попробуй сам): раскомментируй — объект не сопротивляется.
   */
  // note.title = "";                   // получается!
  // note.isPinned = !note.isPinned;    // получается!
  // console.log("[object+functions] Сломанная заметка:", note);
}

/**
 * ============================================================
 * ШАГ 2. ПРОВЕРКИ НА ПРОЧНОСТЬ
 * ============================================================
 * Мы собрали данные в объект. Стало ли лучше? Проверим.
 */

/**
 * СИТУАЦИЯ 1. Заметка всё ещё «пассажир»
 * ---------------------------------------
 * Посмотри на вызовы:
 *
 *   renameNote(note, "...")
 *   addTagToNote(note, "...")
 *   pinNote(note)
 *
 * Заметка не делает ничего сама. Её ПЕРЕДАЮТ в функцию, функция
 * её меняет и отдаёт обратно. Объект — просто контейнер, который
 * таскают между функциями. Поведение по-прежнему ЖИВЁТ СНАРУЖИ.
 *
 * Вопрос: что по сути изменилось по сравнению с Задачей 1?
 * Данные теперь в одном месте. Но функция всё так же знает
 * про заметку больше, чем сама заметка.
 */

/**
 * СИТУАЦИЯ 2. Объект всё ещё можно сломать
 * ----------------------------------------
 * Поля объекта доступны всем. Ты только что пробовал:
 *
 *   note.title = "";
 *   note.isPinned = !note.isPinned;
 *
 * Объект не сопротивляется. Он не знает, что его ломают.
 * Сборка данных в объект НЕ добавила защиты.
 */

/**
 * СИТУАЦИЯ 3. Где живут действия с заметкой?
 * ------------------------------------------
 * Чтобы понять, что можно сделать с заметкой, тебе снова нужно
 * искать функции по файлу: renameNote, addTagToNote, pinNote...
 * Объект не подскажет. Он молчит.
 *
 * Объект пока — просто коробка с данными.
 */

/**
 * ПАУЗА. СФОРМУЛИРУЙ ДЛЯ СЕБЯ
 * ---------------------------
 *   1. Поведение теперь внутри объекта или всё ещё снаружи?
 *   2. Может ли объект защитить свои данные?
 *   3. Подскажет ли объект, какие действия над ним возможны?
 *
 * Если ответы: «снаружи», «нет», «нет» — значит, объекта
 * как контейнера НЕДОСТАТОЧНО. Нужно, чтобы объект сам
 * содержал своё поведение.
 */

/**
 * ============================================================
 * ШАГ 3. ОБЪЕКТ + МЕТОДЫ (поведение переезжает внутрь)
 * ============================================================
  * Теперь заметка сама содержит свои действия. Это методы —
 * функции, которые живут ВНУТРИ объекта и работают с ЕГО данными.
 *
 * Классы здесь пока не нужны: объект с методами можно создать
 * фабричной функцией. К классам мы придём позже.
 * Как спрятать поля? В классе это сделают private, а пока — через замыкание фабричной функции.
 */
namespace ObjectPlusMethods {
  /**
   * Фабрика создаёт заметку и сразу даёт ей поведение.
   * Данные закрыты в замыкании: снаружи до них не добраться.
   */
  function createNote(
    id: number,
    initialTitle: string,
    initialContent: string,
    initialTags: string[]
  ) {
    /** Состояние заметки. Доступно только методам ниже. */
    let title = initialTitle;
    let content = initialContent;
    let tags = [...initialTags];
    let isPinned = false;

    /** Внутренняя проверка заголовка — одна на все случаи. */
    function setTitle(value: string): void {
      const trimmed = value.trim();
      if (!trimmed) {
        throw new Error("Заголовок заметки не может быть пустым");
      }
      title = trimmed;
    }

    /**
     * Объект, который возвращает фабрика.
     * Данные + поведение живут вместе.
     */
    return {
      id,

      rename(newTitle: string): void {
        setTitle(newTitle); // правило применяется само
      },

      addTag(tag: string): void {
        if (!tags.includes(tag)) {
          tags.push(tag);
        }
      },

      pin(): void {
        isPinned = true;
      },

      unpin(): void {
        isPinned = false;
      },

      /** Отдаём копию, чтобы снаружи не смогли изменить состояние. */
      getData() {
        return {
          id,
          title,
          content,
		  /** Если вернуть tags напрямую, снаружи смогут сделать note.getData().tags.push("мусор"). Поэтому отдаём копию.*/
          tags: [...tags],
          isPinned,
        };
      },
    };
  }

  /** Использование: заметка ДЕЙСТВУЕТ САМА. */
  const note = createNote(1, "Идеи проекта", "Сделать менеджер задач", ["работа"]);
  note.rename("Идеи для нового проекта"); // заметка сама себя переименовывает
  note.addTag("важное");
  note.pin();

  /**
   * Сломать не получится: переменные title, tags и другие закрыты
   * в замыкании фабрики. Снаружи их просто нет.
   */
  // note.title = "";    // ❌ нет такого поля снаружи

  console.log("[object+methods] Заметка:", note.getData());
}

/**
 * ============================================================
 * ШАГ 4. ТЕ ЖЕ ПРОВЕРКИ
 * ============================================================
 *
 * СИТУАЦИЯ 1. Заметка больше не «пассажир»
 * Теперь заметка ДЕЙСТВУЕТ САМА: note.rename(...), note.pin().
 * Её не передают в функции — она сама знает, как себя менять.
 * Поведение переехало внутрь.
 *
 * СИТУАЦИЯ 2. Объект защищает данные
 * Состояние закрыто в замыкании фабрики. Снаружи нельзя написать
 * note.title = "" — такого поля просто нет. Правило «непустой
 * заголовок» проверяется в одном месте — в setTitle.
 *
 * СИТУАЦИЯ 3. Объект подсказывает свои возможности
 * Открой объект, который возвращает фабрика, и ты сразу видишь:
 * rename, addTag, pin, unpin, getData. Вот всё, что можно сделать.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Что изменилось по сравнению с Задачей 1:
 *   - данные заметки собраны в один объект;
 *   - поведение переехало ВНУТРЬ объекта (методы);
 *   - объект стал владельцем своих правил и данных.
 *
 * Главный вывод этой задачи:
 *   Просто собрать данные в объект — НЕДОСТАТОЧНО.
 *   Объект-контейнер с функциями вокруг — та же проблема,
 *   только в красивой обёртке. Настоящий объект объединяет
 *   данные И поведение, и сам отвечает за своё состояние.
 *
 * Ситуация               | Объект + функции          | Объект + методы
 * -----------------------|---------------------------|---------------------------
 * Поведение              | снаружи, в функциях       | внутри, в методах
 * Заметка при изменении  | пассивный «пассажир»      | действует сама
 * Защита данных          | нет, поля открыты         | есть, замыкание
 * «Что можно сделать?»   | искать функции по файлу   | видно по объекту
 *
 * Дальше посмотрим, что происходит, когда функций вокруг объекта
 * становится слишком много — и почему это сигнал, что поведение
 * пора переселять внутрь навсегда.
 * В следующей задаче увидим, что происходит, когда функций вокруг объекта становится больше.
 */