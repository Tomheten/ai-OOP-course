/**
 * ============================================================
 * ШАГ 1. ПРИЛОЖЕНИЕ ИЗ ОБЪЕКТОВ
 * ============================================================
 */
namespace ComposedApplication {
  type Order = { id: number; item: string; amount: number };

  /** Логирование. */
  class Logger {
    log(message: string): void {
      console.log(`[LOG] ${message}`);
    }
  }

  /** Хранение. */
  class OrderStorage {
    private orders: Map<number, Order> = new Map();

    save(order: Order): void {
      this.orders.set(order.id, order);
    }

    count(): number {
      return this.orders.size;
    }
  }

  /** Конфигурация. */
  class ConfigProvider {
    private taxRate = 0.2;

    getTaxRate(): number {
      return this.taxRate;
    }
  }

  /** Уведомления. */
  class Notifier {
    notify(message: string): void {
      console.log(`[NOTIFY] ${message}`);
    }
  }

  /**
   * Сервис заказа. Содержит ЧЕТЫРЕ зависимости.
   * Каждая отвечает за своё. Сервис координирует.
   */
  class OrderService {
    constructor(
      private readonly logger: Logger,
      private readonly storage: OrderStorage,
      private readonly config: ConfigProvider,
      private readonly notifier: Notifier
    ) {}

    createOrder(item: string, amount: number): Order {
      const order: Order = { id: Date.now(), item, amount };
      this.storage.save(order);
      this.logger.log(`создан заказ ${order.id}`);
      this.notifier.notify(`Заказ ${order.id} создан`);
      return order;
    }

    calculateTotal(order: Order): number {
      return order.amount * (1 + this.config.getTaxRate());
    }
  }

  /** Точка сборки приложения. */
  const logger = new Logger();
  const storage = new OrderStorage();
  const config = new ConfigProvider();
  const notifier = new Notifier();

  const app = new OrderService(logger, storage, config, notifier);

  const order = app.createOrder("Книга", 500);
  console.log("[app] итого:", app.calculateTotal(order));
  console.log("[app] заказов:", storage.count());
}

