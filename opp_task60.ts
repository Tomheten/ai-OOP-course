/**
 * СИТУАЦИЯ 1. Приложение — это граф объектов
 * ------------------------------------------
 * Приложение не один большой класс. Это много маленьких объектов,
 * соединённых через композицию. Каждый делает своё.
 */

/**
 * СИТУАЦИЯ 2. Поведение собирается из частей
 * ------------------------------------------
 * Сложное поведение сервиса — это сумма делегирований: логгер
 * логирует, хранилище хранит, конфиг даёт настройки, нотификатор
 * уведомляет. Сервис только координирует.
 */

/**
 * СИТУАЦИЯ 3. Никаких цепочек наследования
 * ----------------------------------------
 * Мы построили всё это без единого `extends`. Объекты сотрудничают,
 * а не наследуются друг от друга.
 */

/**
 * ============================================================
 * ИТОГ БЛОКА 8
 * ============================================================
 *
 * Главная мысль блока:
 *   Большая система строится через СОТРУДНИЧЕСТВО ОБЪЕКТОВ,
 *   а не через длинные цепочки наследования.
 *
 * Композиция даёт:
 *   - разделение ответственностей;
 *   - возможность подменять части;
 *   - гибкость без наследования;
 *   - понятную структуру приложения.
 *
 * Ситуация              | Один большой класс     | Композиция
 * ----------------------|------------------------|---------------------------
 * Ответственности       | все в одном            | разделены
 * Изменение поведения   | править класс          | подменить объект
 * Структура             | запутанная             | граф объектов
 * Наследование          | часто нужно            | не нужно
 *
 * Блок 8 завершён.
 *
 * Дальше — дополнительный блок про наследование. Мы посмотрим,
 * где оно уместно, а где — нет, и почему композиция обычно
 * оказывается лучше.
 */