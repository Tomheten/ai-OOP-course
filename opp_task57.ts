/**
 * ============================================================
 * ШАГ 1. НЕСКОЛЬКО ЗАВИСИМОСТЕЙ
 * ============================================================
 * Сервис содержит и логгер, и хранилище. Обе зависимости
 * передаются через конструктор.
 */
namespace MultipleDependencies {
  type Order = { id: number; item: string; amount: number };

  /** Ответственность: логирование. */
  class Logger {
    log(message: string): void {
      console.log(`[LOG] ${message}`);
    }
  }

  /** Ответственность: хранение заказов. */
  class OrderStorage {
    private orders: Map<number, Order> = new Map();

    save(order: Order): void {
      this.orders.set(order.id, order);
    }

    findById(id: number): Order | undefined {
      return this.orders.get(id);
    }

    count(): number {
      return this.orders.size;
    }
  }

  /** Сервис содержит ДВЕ зависимости. */
  class OrderService {
    constructor(
      private readonly logger: Logger,
      private readonly storage: OrderStorage
    ) {}

    createOrder(item: string, amount: number): Order {
      const order: Order = { id: Date.now(), item, amount };
      this.storage.save(order);       // делегируем хранение
      this.logger.log(`создан заказ ${order.id}`); // делегируем логирование
      return order;
    }

    getOrder(id: number): Order | undefined {
      return this.storage.findById(id); // делегируем поиск
    }
  }

  /** Собираем систему из трёх объектов. */
  const logger = new Logger();
  const storage = new OrderStorage();
  const service = new OrderService(logger, storage);

  const order = service.createOrder("Книга", 500);
  console.log("[multi] заказов в хранилище:", storage.count());
  console.log("[multi] найден:", service.getOrder(order.id)?.item);
}

