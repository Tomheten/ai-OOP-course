/**
 * ============================================================
 * ШАГ 2. ШЕСТЬ КЛЮЧЕВЫХ КОНЦЕПЦИЙ
 * ============================================================
 */

/**
 * КОНЦЕПЦИЯ 1. ОТВЕТСТВЕННОСТЬ
 * -----------------------------
 * Каждый объект и каждый класс отвечает за одно дело.
 * Правило живёт там, где живут данные, которые оно защищает.
 *
 * Вопрос для проверки: «Кто должен это знать?»
 */

/**
 * КОНЦЕПЦИЯ 2. ИНКАПСУЛЯЦИЯ
 * --------------------------
 * Объект скрывает своё состояние и защищает его. Изменить
 * состояние можно только через методы, которые знают правила.
 *
 * Вопрос для проверки: «Можно ли сломать объект извне?»
 */

/**
 * КОНЦЕПЦИЯ 3. RICH DOMAIN MODEL
 * -------------------------------
 * Сущность знает свои бизнес-правила и защищает свои инварианты.
 * Противоположность — анемичная модель, где сущность пустая,
 * а логика размазана по сервисам.
 *
 * Вопрос для проверки: «Знает ли объект свои правила?»
 */

/**
 * КОНЦЕПЦИЯ 4. ПОЛИМОРФИЗМ
 * -------------------------
 * Разные реализации используются одинаково через общий контракт.
 * Клиент работает через абстракцию и не знает конкретного типа.
 *
 * Вопрос для проверки: «Есть ли в клиенте выбор по типу?»
 */

/**
 * КОНЦЕПЦИЯ 5. КОМПОЗИЦИЯ
 * ------------------------
 * Объект содержит другие объекты и делегирует им работу.
 * Поведение собирается из частей, а не наследуется.
 *
 * Вопрос для проверки: «Отношение "имеет" или "является"?»
 */

/**
 * КОНЦЕПЦИЯ 6. НАСЛЕДОВАНИЕ
 * --------------------------
 * Создание нового класса на основе существующего. Уместно для
 * стабильных отношений «является» и иерархий ошибок. В остальных
 * случаях обычно лучше композиция.
 *
 * Вопрос для проверки: «Точно ли это "является", а не "имеет"?»
 */

/**
 * ============================================================
 * ШАГ 3. КОГДА ЧТО ИСПОЛЬЗОВАТЬ
 * ============================================================
 */

/**
 * ИНКАПСУЛЯЦИЯ — всегда.
 *   Объект должен защищать своё состояние.
 *
 * ОТВЕТСТВЕННОСТЬ — всегда.
 *   Одна ответственность на класс. Правило рядом с данными.
 *
 * RICH DOMAIN MODEL — когда у сущности есть бизнес-правила.
 *   Не выноси правила в сервисы, если они про состояние сущности.
 *
 * ПОЛИМОРФИЗМ — когда есть несколько реализаций одного действия.
 *   Вместо выбора по типу — общий контракт.
 *
 * КОМПОЗИЦИЯ — когда нужно собрать поведение из частей.
 *   Отношение «имеет». Гибкое комбинирование.
 *
 * НАСЛЕДОВАНИЕ — когда отношение «является» стабильно.
 *   Иерархии ошибок, небольшое число уровней.
 */

