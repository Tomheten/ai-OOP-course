/**
 * ============================================================
 * ШАГ 1. ОБЩИЙ КОНТРАКТ
 * ============================================================
 */
namespace NotificationRendererInterface {
  /**
   * ИНТЕРФЕЙС — общий контракт рендерера уведомлений.
   * Любой класс, который умеет отображать уведомление,
   * может реализовать этот контракт.
   */
  interface NotificationRenderer {
    render(message: string): string;
  }

  class EmailRenderer implements NotificationRenderer {
    render(message: string): string {
      return `[EMAIL] ${message}`;
    }
  }

  class WarningRenderer implements NotificationRenderer {
    render(message: string): string {
      return `⚠️ ВНИМАНИЕ: ${message}`;
    }
  }

  class SuccessRenderer implements NotificationRenderer {
    render(message: string): string {
      return `✅ УСПЕХ: ${message}`;
    }
  }

  /**
   * Клиент работает через контракт.
   * Ему не важно, какой именно рендерер передан.
   */
  function showNotification(renderer: NotificationRenderer, message: string): void {
    console.log(renderer.render(message));
  }

  showNotification(new EmailRenderer(), "Файл загружен");
  showNotification(new WarningRenderer(), "Мало места");
  showNotification(new SuccessRenderer(), "Операция завершена");
}

