/**
 * ============================================================
 * ШАГ 1. USER И СЕРВИС
 * ============================================================
 */
namespace WithUserService {
  type UserRole = "user" | "admin";
  type UserStatus = "active" | "banned" | "pending";

  /** User по-прежнему — только данные. */
  class User {
    id: number;
    name: string;
    email: string;
    role: UserRole;
    status: UserStatus;

    constructor(id: number, name: string, email: string, role: UserRole, status: UserStatus) {
      this.id = id;
      this.name = name;
      this.email = email;
      this.role = role;
      this.status = status;
    }
  }

  /** А всё поведение теперь живёт здесь. */
  class UserService {
    updateName(user: User, newName: string): void {
      user.name = newName;
    }

    banUser(user: User): void {
      user.status = "banned";
    }

    promoteToAdmin(user: User): void {
      user.role = "admin";
    }
  }

  const user = new User(1, "Иван", "ivan@example.com", "user", "active");
  const service = new UserService();

  service.updateName(user, "Иван Петров");
  service.banUser(user);
  console.log("[user-service]", user);
}

