/**
 * СИТУАЦИЯ 1. User ничего не умеет
 * --------------------------------
 * Посмотри на класс User: он по-прежнему коробка с данными.
 * Вся логика — в UserService. User не знает, как его менять.
 */

/**
 * СИТУАЦИЯ 2. Сервис можно обойти
 * -------------------------------
 * Раз поля открыты, любой код может сделать то же самое напрямую:
 *
 *   user.status = "banned";
 *
 * Зачем тогда UserService? Он не обязателен. Его легко
 * проигнорировать.
 */

/**
 * СИТУАЦИЯ 3. Поведение оторвано от данных
 * ----------------------------------------
 * Данные живут в User, поведение — в UserService. Это две разные
 * сущности, которые работают в паре, но ничего друг о друге не
 * знают. Если поменять структуру User, нужно помнить, что есть
 * сервис, который с ним работает.
 */

