namespace CsvParserImplementation {
  type Record = {
    id: number;
    name: string;
    value: number;
  };

  interface Parser {
    parse(content: string): Record[];
  }

  /**
   * CsvParser реализует контракт.
   * Он знает, как превратить CSV-строку в массив записей.
   *
   * Формат:
   *   id,name,value
   *   1,Первый,100
   *   2,Второй,200
   *
   * Первая строка — заголовки, остальные — данные.
   */
  class CsvParser implements Parser {
    parse(content: string): Record[] {
      const lines = content.trim().split("\n");
      /**
       * Пропускаем заголовки. В реальном коде можно было бы
       * читать их и сопоставлять с полями записи. Здесь
       * упрощаем: считаем, что порядок известен.
       */
      return lines.slice(1).map((line) => {
        const [id, name, value] = line.split(",");
        return {
          id: Number(id),
          name: name.trim(),
          value: Number(value),
        };
      });
    }
  }

  const csvContent = `id,name,value
1,Первый,100
2,Второй,200
3,Третий,300`;

  const parser = new CsvParser();
  const records = parser.parse(csvContent);

  console.log("[csv-parser] записей:", records.length);
  console.log("[csv-parser] первая:", records[0]);
}

