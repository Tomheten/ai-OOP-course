/**
 * ============================================================
 * ЗАДАЧА 56. LOGGER ВНУТРИ СЕРВИСА
 * Блок 8. Композиция
 * ============================================================
 *
 * Мы умеем выделять ответственности в отдельные классы. Теперь
 * посмотрим, КАК объекты соединяются друг с другом.
 *
 * Композиция — это когда один объект СОДЕРЖИТ другой и пользуется
 * им. Это отношение «имеет» (has-a): у сервиса ЕСТЬ логгер.
 *
 * ЗАДАНИЕ:
 *   - Вынеси логирование из сервиса в отдельный объект.
 *   - Свяжи их через композицию.
 *
 * Читай файл сверху вниз. Запусти его и посмотри на вывод.
 */

/**
 * ============================================================
 * ШАГ 1. ЛОГИРОВАНИЕ ВНУТРИ СЕРВИСА (БЫЛО)
 * ============================================================
 * Сервис делает всё сам: и заказы обрабатывает, и логи пишет.
 */
namespace LoggingInline {
  type Order = { id: number; item: string; amount: number };

  /** Сервис тащит на себе и логику, и логирование. */
  class OrderService {
    createOrder(item: string, amount: number): Order {
      const order: Order = { id: Date.now(), item, amount };
      /** Логирование размазано по методам. */
      console.log(`[LOG] создан заказ ${order.id}`);
      return order;
    }

    cancelOrder(order: Order): void {
      console.log(`[LOG] отменён заказ ${order.id}`);
    }
  }

  const service = new OrderService();
  const order = service.createOrder("Книга", 500);
  service.cancelOrder(order);
}

/**
 * ============================================================
 * ШАГ 2. ПРОВЕРКИ: ЧТО НЕ ТАК
 * ============================================================
 */

/**
 * СИТУАЦИЯ 1. Сервис делает две вещи
 * ----------------------------------
 * Посмотри на OrderService. Он обрабатывает заказы И пишет логи.
 * Это две ответственности в одном классе.
 */

/**
 * СИТУАЦИЯ 2. Логирование нельзя поменять
 * ----------------------------------------
 * Если завтра нужно писать логи в файл или отправлять в сервис
 * мониторинга, придётся менять каждый метод сервиса. Логирование
 * «зашито» внутрь.
 */

/**
 * СИТУАЦИЯ 3. Знакомая идея
 * -------------------------
 * Мы уже выделяли ответственности в Блоке 5. Здесь мы делаем
 * следующий шаг: не просто выделяем класс, а СОЕДИНЯЕМ его с
 * сервисом через композицию.
 */

/**
 * ============================================================
 * ШАГ 3. ЛОГГЕР КАК ОТДЕЛЬНЫЙ ОБЪЕКТ (СТАЛО)
 * ============================================================
 * Выделяем логирование в отдельный класс и соединяем через
 * композицию: сервис СОДЕРЖИТ логгер.
 */
namespace LoggingComposed {
  type Order = { id: number; item: string; amount: number };

  /** Отдельная ответственность: логирование. */
  class Logger {
    log(message: string): void {
      console.log(`[LOG] ${message}`);
    }
  }

  /** Сервис СОДЕРЖИТ логгер. Отношение «имеет». */
  class OrderService {
    /** Композиция: логгер — часть сервиса. */
    private readonly logger: Logger;

    constructor(logger: Logger) {
      this.logger = logger;
    }

    createOrder(item: string, amount: number): Order {
      const order: Order = { id: Date.now(), item, amount };
      /** Сервис не знает, КАК работает логгер. Просто пользуется. */
      this.logger.log(`создан заказ ${order.id}`);
      return order;
    }

    cancelOrder(order: Order): void {
      this.logger.log(`отменён заказ ${order.id}`);
    }
  }

  /** Собираем объекты вместе. Это и есть композиция. */
  const logger = new Logger();
  const service = new OrderService(logger);

  const order = service.createOrder("Книга", 500);
  service.cancelOrder(order);
}

/**
 * ============================================================
 * ШАГ 4. СРАВНЕНИЕ
 * ============================================================
 */

/**
 * СИТУАЦИЯ 1. Каждая ответственность — свой объект
 * -------------------------------------------------
 * Логирование живёт в Logger. Логика заказов — в OrderService.
 * Сервис больше не делает две вещи.
 */

/**
 * СИТУАЦИЯ 2. Сервис не знает деталей логирования
 * -----------------------------------------------
 * Сервис просто вызывает logger.log(). Ему не важно, пишет ли
 * логгер в консоль, в файл или в сеть. Это дело логгера.
 */

/**
 * СИТУАЦИЯ 3. Логгер можно подменить
 * -----------------------------------
 * Раз сервис работает с логгером через метод, мы можем передать
 * другой логгер (например, файловый), не меняя сервис.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Композиция — это когда объект СОДЕРЖИТ другой объект и
 * пользуется им. У сервиса ЕСТЬ логгер.
 *
 * Ситуация              | Логирование внутри   | Композиция
 * ----------------------|----------------------|---------------------------
 * Ответственностей      | 2 в одном классе     | 1 + 1
 * Сменить логирование   | править сервис       | подменить логгер
 * Связь                 | зашито               | через объект
 *
 * Дальше добавим вторую зависимость — хранилище — и увидим,
 * как композиция масштабируется.
 */