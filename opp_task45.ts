/**
 * Посмотри на три импортера из предыдущих задач:
 *
 *   JsonImporter.import(content: string): Record[]
 *   CsvImporter.import(content: string): Record[]
 *   TxtImporter.import(content: string): Record[]
 *
 * У всех одна и та же сигнатура. Это и есть общий контракт:
 * «любой парсер принимает строку и возвращает массив записей».
 */

/**
 * ============================================================
 * ШАГ 2. ВВОДИМ ИНТЕРФЕЙС
 * ============================================================
 */
namespace ParserInterface {
  type Record = {
    id: number;
    name: string;
    value: number;
  };

  /**
   * ИНТЕРФЕЙС — общий контракт парсера.
   * Любой класс, который умеет разбирать содержимое файла,
   * может реализовать этот контракт.
   */
  interface Parser {
    parse(content: string): Record[];
  }

  /** Первая реализация контракта. */
  class JsonParser implements Parser {
    parse(content: string): Record[] {
      return JSON.parse(content);
    }
  }

  /** Вторая реализация контракта. */
  class CsvParser implements Parser {
    parse(content: string): Record[] {
      const lines = content.trim().split("\n");
      return lines.slice(1).map((line) => {
        const [id, name, value] = line.split(",");
        return { id: Number(id), name: name.trim(), value: Number(value) };
      });
    }
  }

  /** Третья реализация контракта. */
  class TxtParser implements Parser {
    parse(content: string): Record[] {
      return content
        .trim()
        .split("\n")
        .map((line) => {
          const [id, name, value] = line.split("|");
          return { id: Number(id), name: name.trim(), value: Number(value) };
        });
    }
  }

  /**
   * Клиент работает ЧЕРЕЗ КОНТРАКТ.
   * Ему не важно, какой именно парсер передан.
   */
  function importData(parser: Parser, content: string): Record[] {
    return parser.parse(content);
  }

  const jsonContent = JSON.stringify([{ id: 1, name: "Первый", value: 100 }]);
  const csvContent = "id,name,value\n2,Второй,200";
  const txtContent = "3|Третий|300";

  console.log("[parser] json:", importData(new JsonParser(), jsonContent));
  console.log("[parser] csv:", importData(new CsvParser(), csvContent));
  console.log("[parser] txt:", importData(new TxtParser(), txtContent));
}

