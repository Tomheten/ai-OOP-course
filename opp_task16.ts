/**
 * ============================================================
 * ШАГ 1. БЫЛО: ДЕЙСТВИЯ ВОКРУГ ОБЪЕКТА
 * ============================================================
 * То, к чему мы пришли в Задаче 15.
 */
namespace TodoFunctionsRecap {
  type TodoStatus = "active" | "completed";

  type Todo = {
    id: number;
    title: string;
    status: TodoStatus;
    createdAt: string;
  };

  let nextId = 1;

  function createTodo(title: string): Todo {
    return {
      id: nextId++,
      title,
      status: "active",
      createdAt: new Date().toISOString(),
    };
  }

  /** Действия — снаружи, принимаю́т Todo аргументом. */
  function completeTodo(todo: Todo): void {
    todo.status = "completed";
  }

  function reopenTodo(todo: Todo): void {
    todo.status = "active";
  }

  function renameTodo(todo: Todo, title: string): void {
    todo.title = title;
  }

  const todo = createTodo("Купить молоко");
  completeTodo(todo);
  console.log("[recap] статус:", todo.status);
}

