/**
 * СИТУАЦИЯ 1. Действия не принадлежат Todo
 * ----------------------------------------
 * completeTodo, reopenTodo, renameTodo живут отдельно. Ничто не
 * мешает написать рядом ещё десять функций, которые что-то делают
 * с Todo, — и сам Todo об этом ничего не узнает.
 */

/**
 * СИТУАЦИЯ 2. Состояние открыто
 * -----------------------------
 * В Шаге 1 любой код может написать `todo.status = "completed"`,
 * минуя функции. Поведение снаружи, данные открыты — объект пока
 * не хозяин своего состояния.
 */

/**
 * ============================================================
 * ШАГ 3. СТАЛО: ДЕЙСТВИЯ ВНУТРИ КЛАССА
 * ============================================================
 * Переносим поведение внутрь. Пока делаем первый шаг: действия
 * становятся методами. Защиту состояния добавим в следующей задаче.
 */
namespace TodoAsObject {
  type TodoStatus = "active" | "completed";

  class Todo {
    id: number;
    title: string;
    status: TodoStatus;
    createdAt: string;

    constructor(id: number, title: string) {
      this.id = id;
      this.title = title;
      this.status = "active";
      this.createdAt = new Date().toISOString();
    }

    /** Действия теперь методы — принадлежат самому Todo. */
    complete(): void {
      this.status = "completed";
    }

    reopen(): void {
      this.status = "active";
    }

    rename(title: string): void {
      this.title = title;
    }
  }

  const todo = new Todo(1, "Купить молоко");
  todo.complete();
  console.log("[todo-as-object] статус:", todo.status);

  /**
   * НО: поля пока открыты. Раскомментируй — и состояние можно
   * поменять в обход методов. Это разберём в следующей задаче.
   */
  // todo.status = "active";   // всё ещё получается
  // todo.title = "";          // и это получается
}

