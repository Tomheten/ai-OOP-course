/**
 * ============================================================
 * ШАГ 1. КОНФИГУРАЦИЯ ЗАХАРДКОЖЕНА (БЫЛО)
 * ============================================================
 */
namespace ConfigHardcoded {
  type Order = { id: number; item: string; amount: number };

  class OrderService {
    /** Настройки зашиты прямо в сервис. */
    private readonly taxRate = 0.2;

    calculateTotal(order: Order): number {
      return order.amount * (1 + this.taxRate);
    }
  }

  const service = new OrderService();
  console.log("[hardcoded] итог:", service.calculateTotal({ id: 1, item: "Книга", amount: 500 }));
}

