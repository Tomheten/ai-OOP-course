/**
 * СИТУАЦИЯ 2. Разные окружения — разная конфигурация
 * ---------------------------------------------------
 * В тестах налог может быть 0, в продакшене 0.2. Если настройки
 * зашиты, это невозможно.
 */

/**
 * ============================================================
 * ШАГ 3. КОНФИГУРАЦИЯ ЧЕРЕЗ ПРОВАЙДЕР (СТАЛО)
 * ============================================================
 */
namespace ConfigProviderComposed {
  type Order = { id: number; item: string; amount: number };

  /** Ответственность: предоставлять настройки. */
  class ConfigProvider {
    private values: Map<string, number> = new Map();

    set(key: string, value: number): void {
      this.values.set(key, value);
    }

    get(key: string): number {
      const value = this.values.get(key);
      if (value === undefined) {
        throw new Error(`Нет настройки: ${key}`);
      }
      return value;
    }
  }

  /** Сервис пользуется провайдером через композицию. */
  class OrderService {
    constructor(private readonly config: ConfigProvider) {}

    calculateTotal(order: Order): number {
      /** Сервис не знает, откуда берутся настройки. */
      const taxRate = this.config.get("taxRate");
      return order.amount * (1 + taxRate);
    }
  }

  /** Собираем систему. Настройки можно менять снаружи. */
  const config = new ConfigProvider();
  config.set("taxRate", 0.2);

  const service = new OrderService(config);
  console.log("[provider] итог:", service.calculateTotal({ id: 1, item: "Книга", amount: 500 }));

  /** Для тестов легко поменять конфигурацию. */
  config.set("taxRate", 0);
  console.log("[provider] итог без налога:", service.calculateTotal({ id: 1, item: "Книга", amount: 500 }));
}

