/**
 * ============================================================
 * ШАГ 5. ГЛАВНЫЙ ВЫВОД БЛОКА
 * ============================================================
 *
 * Большинство правил о пользователе — это правила про его
 * собственное состояние. Значит, знать их должен сам User.
 *
 * Когда правила, которые опираются только на состояние сущности,
 * вынесены в отдельные сервисы — это признак анемичной модели.
 *
 * Правильное распределение:
 *   - сущность знает свои инварианты и правила перехода;
 *   - сервисы занимаются тем, что требует внешних знаний:
 *     работа с БД, отправка писем, интеграции.
 *
 * Сервисы не должны знать, как правильно поменять поле
 * пользователя. Это дело самого пользователя.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Мы нашли хозяев правил:
 *   - правила, опирающиеся только на состояние сущности, —
 *     в сущности;
 *   - правила, требующие внешних знаний, — в сервисах.
 *
 * В нашей системе почти все правила должны были жить в User,
 * а не в четырёх сервисах вокруг.
 *
 * Дальше перенесём поведение внутрь User и получим Rich Domain
 * Model — богатую, живую модель вместо анемичной.
 */