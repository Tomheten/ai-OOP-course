/**
 * СИТУАЦИЯ 1. Хранение — отдельная ответственность
 * -------------------------------------------------
 * Если завтра нужно будет хранить заметки в базе, в файле,
 * в облаке — придётся менять редактор. Хотя редактор не должен
 * знать, КАК хранятся заметки.
 */

/**
 * СИТУАЦИЯ 2. Нельзя подменить способ хранения
 * ---------------------------------------------
 * В тестах хочется использовать простое хранилище в памяти.
 * В продакшене — базу. Если хранение зашито в редактор, это
 * невозможно.
 */

/**
 * ============================================================
 * ШАГ 3. ХРАНИЛИЩЕ КАК ОТДЕЛЬНЫЙ КЛАСС
 * ============================================================
 */
namespace StorageAsSeparateClass {
  class Note {
    private title: string;

    constructor(title: string) {
      this.title = title;
    }

    getTitle(): string {
      return this.title;
    }
  }

  /** Отдельная ответственность: хранение заметок. */
  class NoteStore {
    private notes: Map<number, Note> = new Map();
    private nextId = 1;

    add(note: Note): number {
      const id = this.nextId++;
      this.notes.set(id, note);
      return id;
    }

    findById(id: number): Note | undefined {
      return this.notes.get(id);
    }

    getAll(): Note[] {
      return Array.from(this.notes.values());
    }

    remove(id: number): void {
      this.notes.delete(id);
    }
  }

  /** Редактор использует хранилище, но не владеет логикой хранения. */
  class NoteEditor {
    private readonly store: NoteStore;

    constructor(store: NoteStore) {
      this.store = store;
    }

    createNote(title: string): Note {
      const note = new Note(title);
      this.store.add(note);
      return note;
    }

    listNotes(): Note[] {
      return this.store.getAll();
    }
  }

  /** Использование: хранилище — отдельный объект. */
  const store = new NoteStore();
  const editor = new NoteEditor(store);

  editor.createNote("Идеи");
  editor.createNote("Покупки");
  console.log("[separate] заметок:", editor.listNotes().length);
}

