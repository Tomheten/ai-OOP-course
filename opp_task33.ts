/**
 * ============================================================
 * ШАГ 1. ХРАНЕНИЕ ВНУТРИ РЕДАКТОРА (БЫЛО)
 * ============================================================
 */
namespace StorageInsideEditor {
  class Note {
    private title: string;

    constructor(title: string) {
      this.title = title;
    }

    getTitle(): string {
      return this.title;
    }
  }

  /** Редактор тащит хранение на себе. */
  class NoteEditor {
    private notes: Note[] = []; // хранение тут же

    add(note: Note): void {
      this.notes.push(note);
    }

    getAll(): Note[] {
      return [...this.notes];
    }

    remove(note: Note): void {
      const index = this.notes.indexOf(note);
      if (index !== -1) this.notes.splice(index, 1);
    }
  }

  const editor = new NoteEditor();
  editor.add(new Note("Идеи"));
  console.log("[inside] заметок:", editor.getAll().length);
}

