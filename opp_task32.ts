/**
 * СИТУАЦИЯ 1. Каждая ответственность — свой класс
 * -----------------------------------------------
 * History отвечает только за историю. Редактор — только за
 * координацию заметок. Чёткое разделение.
 */

/**
 * СИТУАЦИЯ 2. Историю можно переиспользовать
 * ------------------------------------------
 * Нужна история для аудита? Создай History и используй его
 * где хочешь. Не нужен редактор.
 */

/**
 * СИТУАЦИЯ 3. Объекты сотрудничают
 * ---------------------------------
 * Редактор получает историю в конструкторе и пользуется ею.
 * Это пример кооперации объектов: каждый делает своё, вместе
 * они решают задачу.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Мы выделили новую ответственность — историю — в отдельный
 * класс. Это классический приём: если у класса появляется
 * вторая ответственность, её стоит вынести.
 *
 * Ситуация              | История в редакторе  | Отдельный класс
 * ----------------------|----------------------|---------------------------
 * Ответственностей      | 2                    | 1 + 1
 * Переиспользование     | нельзя               | можно
 * Тестирование          | сложнее              | проще
 * Расширяемость         | редактор распухает   | история растёт отдельно
 *
 * Дальше выделим ещё одну ответственность: хранение заметок.
 */