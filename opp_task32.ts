/**
 * ============================================================
 * ШАГ 1. СОБЛАЗН: ИСТОРИЯ В РЕДАКТОРЕ
 * ============================================================
 * Первое, что приходит в голову — хранить историю прямо в
 * NoteEditor. Но посмотрим, к чему это приведёт.
 */
namespace HistoryInsideEditor {
  class Note {
    private title: string;

    constructor(title: string) {
      this.title = title;
    }

    rename(title: string): void {
      this.title = title;
    }

    getTitle(): string {
      return this.title;
    }
  }

  /** Редактор, который тащит историю на себе. */
  class NoteEditor {
    private notes: Note[] = [];
    private history: string[] = []; // история тут же

    createNote(title: string): Note {
      const note = new Note(title);
      this.notes.push(note);
      this.history.push(`Создана заметка "${title}"`);
      return note;
    }

    renameNote(note: Note, title: string): void {
      note.rename(title);
      this.history.push(`Переименована в "${title}"`);
    }

    getHistory(): string[] {
      return [...this.history];
    }
  }

  const editor = new NoteEditor();
  const note = editor.createNote("Идеи");
  editor.renameNote(note, "Новые идеи");
  console.log("[inside] история:", editor.getHistory());
}

/**
 * ============================================================
 * ШАГ 2. ПРОВЕРКИ: ЧТО НЕ ТАК
 * ============================================================
 */

/**
 * СИТУАЦИЯ 1. Две ответственности в одном классе
 * -----------------------------------------------
 * NoteEditor теперь делает две вещи:
 *   - управляет заметками (создание, переименование);
 *   - ведёт историю.
 *
 * Если история станет сложнее (например, с временными метками,
 * авторами, отменой действий) — редактор распухнет.
 */

/**
 * СИТУАЦИЯ 2. Историю нельзя переиспользовать
 * --------------------------------------------
 * Если история понадобится где-то ещё (например, для аудита
 * действий пользователя), вытащить её из редактора будет сложно.
 */

/**
 * СИТУАЦИЯ 3. Тестирование усложняется
 * -------------------------------------
 * Чтобы протестировать редактор, нужно учитывать и историю.
 * Чтобы протестировать историю, нужно городить редактор.
 */

/**
 * ============================================================
 * ШАГ 3. РЕШЕНИЕ: ОТДЕЛЬНЫЙ КЛАСС ДЛЯ ИСТОРИИ
 * ============================================================
 * Выделяем историю в собственный класс. Это отдельная
 * ответственность.
 */
namespace HistoryAsSeparateClass {
  class Note {
    private title: string;

    constructor(title: string) {
      this.title = title;
    }

    rename(title: string): void {
      this.title = title;
    }

    getTitle(): string {
      return this.title;
    }
  }

  /** Отдельная ответственность: хранение истории. */
  class History {
    private entries: { timestamp: string; message: string }[] = [];

    record(message: string): void {
      this.entries.push({
        timestamp: new Date().toISOString(),
        message,
      });
    }

    getEntries(): { timestamp: string; message: string }[] {
      return [...this.entries];
    }
  }

  /** Редактор использует историю, но не владеет её логикой. */
  class NoteEditor {
    private notes: Note[] = [];
    private readonly history: History;

    constructor(history: History) {
      this.history = history; // получили извне
    }

    createNote(title: string): Note {
      const note = new Note(title);
      this.notes.push(note);
      this.history.record(`Создана заметка "${title}"`);
      return note;
    }

    renameNote(note: Note, title: string): void {
      note.rename(title);
      this.history.record(`Переименована в "${title}"`);
    }
  }

  /** Использование: история — отдельный объект. */
  const history = new History();
  const editor = new NoteEditor(history);

  const note = editor.createNote("Идеи");
  editor.renameNote(note, "Новые идеи");

  console.log("[separate] история:", history.getEntries());
}

