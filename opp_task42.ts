/**
 * ============================================================
 * ШАГ 1. НАПОМИНАНИЕ: JSON ИЗ ЗАДАЧИ 41
 * ============================================================
 */
namespace JsonRecap {
  type Record = {
    id: number;
    name: string;
    value: number;
  };

  class JsonImporter {
    import(content: string): Record[] {
      const data = JSON.parse(content);
      return data.map((item: Record) => ({
        id: item.id,
        name: item.name,
        value: item.value,
      }));
    }
  }

  const jsonContent = JSON.stringify([
    { id: 1, name: "Первый", value: 100 },
  ]);

  const importer = new JsonImporter();
  console.log("[json]", importer.import(jsonContent));
}

/**
 * ============================================================
 * ШАГ 2. ДОБАВЛЯЕМ CSV
 * ============================================================
 * CSV — это текстовый формат, где данные разделены запятыми:
 *
 *   id,name,value
 *   1,Первый,100
 *   2,Второй,200
 *
 * Первая строка — заголовки, остальные — данные.
 */
namespace CsvSupport {
  type Record = {
    id: number;
    name: string;
    value: number;
  };

  class JsonImporter {
    import(content: string): Record[] {
      return JSON.parse(content);
    }
  }

  /** Новый класс для CSV. Структура похожа на JsonImporter. */
  class CsvImporter {
    import(content: string): Record[] {
      const lines = content.trim().split("\n");
      // первая строка — заголовки, пропускаем её
      return lines.slice(1).map((line) => {
        const [id, name, value] = line.split(",");
        return {
          id: Number(id),
          name: name.trim(),
          value: Number(value),
        };
      });
    }
  }

  const csvContent = `id,name,value
1,Первый,100
2,Второй,200`;

  const csvImporter = new CsvImporter();
  const records = csvImporter.import(csvContent);
  console.log("[csv] импортировано:", records.length);
  console.log("[csv] первая запись:", records[0]);
}

