/**
 * СИТУАЦИЯ 1. Объекты знают только своё
 * -------------------------------------
 * Заметка знает только про себя. Хранилище знает только про
 * хранение. История — про историю. Автосохранение — про
 * сохранение. Никто не знает обо всех.
 */

/**
 * СИТУАЦИЯ 2. Координатор знает обо всех
 * ---------------------------------------
 * Один объект (координатор) управляет процессом. Если нужно
 * добавить новый шаг (например, отправку уведомления), меняем
 * только координатора.
 */

/**
 * СИТУАЦИЯ 3. Тестировать проще
 * ------------------------------
 * Каждый объект можно тестировать отдельно. Координатор
 * тестируется с моками.
 */

/**
 * ============================================================
 * ИТОГ
 * ============================================================
 *
 * Координация объектов — это выделение одного объекта, который
 * управляет процессом. Остальные объекты делают только своё дело.
 *
 * Признаки плохой координации:
 *   - объект знает о многих других объектах;
 *   - изменение одного объекта требует правки в других;
 *   - трудно тестировать объекты по отдельности.
 *
 * Решение:
 *   - выдели координатора;
 *   - пусть он знает обо всех;
 *   - остальные объекты знают только о себе.
 *
 * Дальше добавим экспорт заметок — новую ответственность.
 */