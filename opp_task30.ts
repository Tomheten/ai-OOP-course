/**
 * ============================================================
 * ШАГ 1. ОДИН И ТОТ ЖЕ СЦЕНАРИЙ В ДВУХ ПОДХОДАХ
 * ============================================================
 * Сценарий: «забанить пользователя».
 */
namespace SideBySide {
  type UserRole = "user" | "admin";
  type UserStatus = "active" | "banned" | "pending";

  /** -------- АНЕМИЧНАЯ ВЕРСИЯ -------- */

  class AnemicUser {
    id: number;
    name: string;
    status: UserStatus;

    constructor(id: number, name: string) {
      this.id = id;
      this.name = name;
      this.status = "active";
    }
  }

  class AnemicUserStatusService {
    ban(user: AnemicUser): void {
      if (user.status !== "active") {
        throw new Error("Только активного");
      }
      user.status = "banned";
    }
  }

  /** Использование анемичной модели. */
  const anemicUser = new AnemicUser(1, "Иван");
  const statusService = new AnemicUserStatusService();
  statusService.ban(anemicUser);
  console.log("[anemic] забанен, статус:", anemicUser.status);

  /** -------- RICH ВЕРСИЯ -------- */

  class RichUser {
    private readonly id: number;
    private name: string;
    private status: UserStatus;

    constructor(id: number, name: string) {
      this.id = id;
      this.name = name;
      this.status = "active";
    }

    ban(): void {
      if (this.status !== "active") {
        throw new Error("Только активного");
      }
      this.status = "banned";
    }

    getStatus(): UserStatus {
      return this.status;
    }
  }

  /** Использование rich-модели. */
  const richUser = new RichUser(1, "Иван");
  richUser.ban();
  console.log("[rich] забанен, статус:", richUser.getStatus());
}

