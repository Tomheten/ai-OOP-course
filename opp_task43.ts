namespace ThreeFormats {
  type Record = {
    id: number;
    name: string;
    value: number;
  };

  /** JSON: [{"id":1,"name":"Первый","value":100}] */
  class JsonImporter {
    import(content: string): Record[] {
      return JSON.parse(content);
    }
  }

  /** CSV: "id,name,value\n1,Первый,100" */
  class CsvImporter {
    import(content: string): Record[] {
      const lines = content.trim().split("\n");
      return lines.slice(1).map((line) => {
        const [id, name, value] = line.split(",");
        return {
          id: Number(id),
          name: name.trim(),
          value: Number(value),
        };
      });
    }
  }

  /** TXT: "1|Первый|100" */
  class TxtImporter {
    import(content: string): Record[] {
      return content
        .trim()
        .split("\n")
        .map((line) => {
          const [id, name, value] = line.split("|");
          return {
            id: Number(id),
            name: name.trim(),
            value: Number(value),
          };
        });
    }
  }

  const txtContent = `1|Первый|100
2|Второй|200`;

  const txtImporter = new TxtImporter();
  const records = txtImporter.import(txtContent);
  console.log("[txt] импортировано:", records.length);
}

